      <!-- Detailed Components -->
      <div class="section-header-center">
        <div class="section-tag">Our Recovery Protocol</div>
        <h2 class="section-heading">What Our Care After a Fall Program Delivers</h2>
        <p class="section-subheading">A comprehensive physical, environmental, and clinical support framework.</p>
      </div>
      <div class="svc-longform">
        <div class="svc-block">
          <span class="svc-block-num">Component 01</span>
          <h3>Room-by-Room Home Safety &amp; Hazard Audit</h3>
          <p>Most falls happen in familiar surroundings. Our registered nurse conducts an exhaustive environmental assessment to eliminate concealed dangers before your loved one takes another unassisted step.</p>
          <ul class="svc-block-list">
            <li>Removal of loose throw rugs, floor cords, and transitional thresholds</li>
            <li>Lighting optimization in hallways, staircases, and bedroom-to-bathroom routes</li>
            <li>Assessment of grab bar locations, shower mats, and raised toilet seats</li>
            <li>Reorganizing daily essentials to eliminate reaching, climbing, and bending</li>
          </ul>
        </div>
        <div class="svc-block">
          <span class="svc-block-num">Component 02</span>
          <h3>Supervised Mobility &amp; Gentle Gait Retraining</h3>
          <p>Our care aides and nurses provide steady physical support for short, frequent walking sessions. We reinforce proper heel-to-toe gait mechanics, posture alignment, and steady pacing prescribed by physiotherapists.</p>
          <ul class="svc-block-list">
            <li>Hands-on transfer support (bed-to-chair, chair-to-standing)</li>
            <li>Supervised indoor and garden walks to rebuild leg muscle endurance</li>
            <li>Practice navigating carpet-to-hardwood transitions and thresholds</li>
            <li>Coordination with community physical and occupational therapists</li>
          </ul>
        </div>
        <div class="svc-block">
          <span class="svc-block-num">Component 03</span>
          <h3>Dignified Personal Care &amp; Hygiene Assistance</h3>
          <p>The bathroom is the highest-risk fall zone in any home. We provide complete, dignified assistance with bathing, shower transfers, dressing, and toileting to ensure total safety during daily routines.</p>
          <ul class="svc-block-list">
            <li>Safe transfer into walk-in showers or onto transfer benches</li>
            <li>Dignified assistance with lower-body washing, drying, and skin protection</li>
            <li>Seated dressing and non-skid footwear verification</li>
            <li>Gentle assistance with nocturnal bathroom visits to prevent night falls</li>
          </ul>
        </div>
        <div class="svc-block">
          <span class="svc-block-num">Component 04</span>
          <h3>Medication Review for Dizziness &amp; Orthostatic Drops</h3>
          <p>Many senior falls are triggered by side effects from blood pressure medications, sedatives, or polypharmacy. Our nursing team tracks blood pressure changes between sitting and standing to catch orthostatic hypotension.</p>
          <ul class="svc-block-list">
            <li>Orthostatic vital sign monitoring (lying, sitting, standing BP)</li>
            <li>Identification of sedating medications or anticholinergic effects</li>
            <li>Direct reporting of dizziness or lightheadedness episodes to physician</li>
            <li>Hydration prompts to maintain vascular volume and cerebral perfusion</li>
          </ul>
        </div>
        <div class="svc-block">
          <span class="svc-block-num">Component 05</span>
          <h3>Fear-of-Falling Psychological Coaching</h3>
          <p>We treat the emotional trauma of a fall with boundless patience. By celebrating small daily milestones and providing continuous calm presence, we help seniors rediscover confidence in their own bodies.</p>
          <ul class="svc-block-list">
            <li>Gentle reassurance without rushing or pressuring</li>
            <li>Progressive goal setting (e.g. walking to the mailbox, eating at the dining table)</li>
            <li>Breathing techniques to reduce transfer-associated anxiety</li>
            <li>Family guidance on encouraging safe activity without hovering</li>
          </ul>
        </div>
        <div class="svc-block">
          <span class="svc-block-num">Component 06</span>
          <h3>24/7 Overnight &amp; Emergency Fall Vigilance</h3>
          <p>Falls frequently recur in the dark when an elder wakes up confused or urgently needing the toilet. We provide dedicated waking-night care to ensure immediate physical support the moment feet touch the floor.</p>
          <ul class="svc-block-list">
            <li>Immediate response to nighttime awakenings and bed exits</li>
            <li>Illuminated, escorted nighttime toileting</li>
            <li>Repositioning support to prevent pressure sores while resting</li>
            <li>Emergency first-aid readiness and immediate family notification</li>
          </ul>
        </div>
      </div>

