          <h2 class="section-heading">Overcoming the Physical and Emotional Aftermath of a Fall</h2>
          <p class="text-paragraph">For an older adult, a fall is rarely just a physical incident. Beyond fractures, contusions, and joint soreness, a fall shatters confidence. Seniors often develop an intense, paralyzing "fear of falling," causing them to restrict their walking, avoid basic household activities, and become prematurely bed- or chair-bound.</p>
