          <h2 id="why-falls">Why Falls Happen More Often Than Families Realize</h2>
          <p>Falls are the leading cause of injury-related hospitalization among Canadian seniors, and roughly half of them happen inside the home. What makes falls so hard to prevent is that they rarely have a single cause. It's usually a combination of a physical change (weaker balance, slower reflexes, poor vision), a medical factor (medication side effects, low blood pressure on standing), and an environmental hazard that, on its own, wouldn't cause a problem for a younger, steadier person.</p>
          <p>The good news is that fall prevention often starts with the environment, which is the easiest piece to fix and doesn't require a renovation budget. Here's the room-by-room walkthrough we recommend to every family we assess.</p>

          <h2 id="entryways">Entryways and Hallways</h2>
          <ul>
            <li>Remove loose mats, runners, and anything with curled edges near the front and back doors.</li>
            <li>Install a secure handrail on any exterior step, even a single one.</li>
            <li>Add motion-sensor or always-on lighting so hallways are never navigated in the dark.</li>
            <li>Clear cords, boxes, and pet bowls from walking paths: the paths people use without thinking are the ones they're least likely to watch closely.</li>
          </ul>

          <h2 id="bathroom">The Bathroom</h2>
          <p>This is the highest-risk room in the house. Wet tile, the physical demand of transferring on and off the toilet, and getting in and out of the tub combine to make bathrooms the most common site of senior falls, especially overnight.</p>
          <ul>
            <li>Install grab bars beside the toilet and inside the tub or shower: towel bars are not a substitute; they aren't rated to bear weight.</li>
            <li>Use a non-slip mat inside the tub and a secured bath mat outside it.</li>
            <li>Consider a raised toilet seat or shower chair if standing balance is a concern.</li>
            <li>Keep a nightlight on so a 2 a.m. bathroom trip doesn't happen in the dark.</li>
          </ul>

          <div class="article-callout">
            <div class="article-callout-title">
              <svg class="icon-sm" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2"><circle cx="12" cy="12" r="10"></circle><line x1="12" y1="16" x2="12" y2="12"></line><line x1="12" y1="8" x2="12.01" y2="8"></line></svg>
              Clinical Tip
            </div>
            <p>If a parent is getting up two or more times a night to use the bathroom, ask their doctor about it. Frequent nighttime urination is both a fall risk on its own and sometimes a sign of an underlying issue worth treating.</p>
          </div>

          <h2 id="bedroom">The Bedroom</h2>
          <ul>
            <li>Keep a lamp and a phone within arm's reach of the bed.</li>
            <li>Set the bed height so feet reach the floor comfortably when sitting on the edge: too high or too low both increase fall risk during transfers.</li>
            <li>Add a clear path, nightlight included, from the bed to the bathroom.</li>
          </ul>

          <h2 id="kitchen">The Kitchen</h2>
          <ul>
            <li>Move frequently used items to waist- or shoulder-height shelves so a step stool isn't needed.</li>
            <li>Wipe spills immediately, and keep a non-slip mat at the sink where splashing is common.</li>
            <li>If a step stool is unavoidable, make sure it has a handrail and a wide, stable base, never a chair.</li>
          </ul>

          <h2 id="stairs">Stairs and Lighting</h2>
          <ul>
            <li>Handrails on both sides of any staircase, extending the full length of the stairs.</li>
            <li>Contrasting tape or paint on the edge of each step to make them easier to judge, particularly if vision has changed.</li>
            <li>Bright, even lighting at both the top and bottom of the stairs: shadowed stairs are a common cause of missed steps.</li>
          </ul>

          <h2 id="footwear">Footwear and Mobility Aids</h2>
          <p>Loose slippers and socks without grip are a surprisingly common contributor to falls. Supportive, closed-back shoes with non-slip soles worn indoors as well as outdoors make a measurable difference. If a cane or walker has been recommended, check that it's the correct height: a mismatched fit undermines the whole point of using it.</p>

          <h2 id="medications">Medications That Increase Fall Risk</h2>
          <p>Several common medication classes, including sedatives, some blood pressure medications, and certain antidepressants, can cause dizziness or a drop in blood pressure on standing. If falls have started happening around the time a new prescription began, or if there's a long list of medications from multiple doctors, a pharmacist-led medication review is worth requesting.</p>

          <h2 id="after-a-fall">What to Do If a Fall Already Happened</h2>
          <p>Even a "minor" fall matters. Check for pain, confusion, or an inability to put weight on a leg before helping someone up, and arrange a medical assessment regardless of how the fall looks. Some injuries, particularly hip fractures and head injuries, aren't obvious right away. Just as importantly, treat the fall as new information: it's a signal to revisit the checklist above and to ask whether some extra <a href="care-after-a-fall">support after a fall</a> would help prevent the next one.</p>

