            <p>When you do visit, resist the urge to tidy up or run errands the whole time. What looks like "helping out" on one visit is also useful information: how much has accumulated since your last visit, and how your parent reacts to you noticing it.</p>
          </div>

          <h2 id="physical">Physical and Mobility Changes to Watch For</h2>
          <p>Watch for a slower, more hesitant walk, increased reliance on furniture for balance, new bruises with no clear explanation, or a general reluctance to move around the house the way they used to. A recent fall, even a minor one they brush off, is one of the more reliable predictors that additional support is needed soon, not eventually.</p>
          <p>Pay attention, too, to whether your parent has quietly stopped doing things that require balance or strength: no longer climbing a step stool, avoiding the bathtub in favor of quick sink washes, or asking someone else to carry anything heavier than a bag of groceries. These small adjustments are often an unconscious way of managing a physical limitation without naming it out loud.</p>

          <h2 id="mail-counter">The Mail Pile and Kitchen Counter Test</h2>
          <p>A stack of unopened mail, expired coupons still sitting on the counter, or a pile of unpaid bills are some of the clearest, least ambiguous signs that daily management has become harder than it used to be. So is a fridge with spoiled or expired food, or a pantry stocked with the same few convenience items because grocery trips have become difficult to manage.</p>
          <p>Financial confusion is worth watching closely as well. Late payment notices, duplicate charitable donations, or unfamiliar purchases can point to genuine difficulty keeping track of money, and in some cases to a scam that's already taken advantage of a parent who's become an easier target than they once were.</p>

          <h2 id="medication">Medication Clues</h2>
          <p>Look at the pill organizer, if there is one, and check whether it matches the day and time it should. Missed doses, doubled-up doses, or a prescription that clearly hasn't been refilled on schedule are strong signals, since medication management requires exactly the kind of routine, multi-step planning that tends to slip first.</p>

          <h2 id="hygiene">Hygiene and Home Upkeep</h2>
          <p>A noticeable change in personal hygiene, wearing the same clothes repeatedly, skipping showers, or a general decline in grooming, often points to a physical difficulty (getting in and out of a shower safely, for instance) rather than simple carelessness. The same is true of a home that's become visibly cluttered or unkempt when it never used to be.</p>
          <p>Look, too, at general household upkeep: an unmowed lawn, overflowing garbage, burnt-out light bulbs left unreplaced, or small maintenance issues that would once have been fixed right away. A home that's slowly falling out of step with how it used to be kept is often the most visible early signal a family gets, precisely because it's easier to notice than a change in a person.</p>

          <h2 id="social">Social Withdrawal</h2>
          <p>A parent who used to see friends regularly, attend church, or call family often and has quietly pulled back may be dealing with more than just "being tired lately." Social withdrawal is sometimes a response to embarrassment about physical decline, a hearing or vision problem making conversation harder, or an early mood change worth paying attention to.</p>
          <p>Driving is another area to watch. New dents on the car, avoiding certain routes or nighttime driving altogether, or friends and family quietly starting to offer rides can all be indirect signs that a parent knows, even if they haven't said so, that something has changed.</p>

          <div class="quote-card-teal">
            <strong>From our clinical experience:</strong> Families often tell us the moment that finally made things click wasn't a fall or a diagnosis. It was something small, spoiled milk in the fridge, a birthday forgotten for the first time, that suddenly reframed months of little things they'd been explaining away.
          </div>

          <h2 id="cognitive">Cognitive Signs That Aren't Necessarily Dementia</h2>
          <p>Not every cognitive change points toward dementia. Confusion, forgetfulness, and disorientation can also stem from a urinary tract infection, medication side effects, thyroid changes, depression, or simple dehydration, all of which are treatable once identified. That said, a pattern of repeated questions, difficulty following conversations, or confusion about the day or time is worth mentioning to a doctor rather than dismissing. If the pattern looks specifically like memory loss rather than general confusion, our guide to the <a href="blog-early-signs-of-dementia">early signs of dementia</a> goes into more detail on what to look for.</p>
          <p>This is exactly why a medical evaluation matters before assuming the worst. A urinary tract infection in an older adult, for example, can produce sudden confusion that looks alarming but often resolves completely with the right treatment. Jumping straight to a dementia diagnosis in your own mind, without ruling out these more treatable causes first, can add unnecessary fear to an already stressful situation.</p>

          <h2 id="what-to-do">What to Do With What You're Noticing</h2>
          <p>One or two of these signs on their own aren't necessarily cause for alarm. A pattern of several, especially ones that are new or getting worse, is worth acting on. Start by talking with your parent directly and gently, and involve their family doctor if something seems medically off rather than simply age-related.</p>
          <p>It can help to write things down as you notice them rather than relying on memory alone. A running list, dates included, turns a vague sense that "something's off" into concrete examples you can share with a doctor, a sibling, or a care professional, and it makes it much easier to see whether a pattern is actually building over time.</p>
          <p>If you're not sure how serious the situation is, a professional, no-pressure perspective can help. A <a href="care-assessment">free in-home care assessment</a> gives you an objective read on safety and daily functioning from someone with clinical training, rather than relying on guesswork from occasional visits or phone calls. And if what you're noticing feels overwhelming to manage alone, know that many families reach this same point long before they expect to. Getting an outside perspective early is far easier than waiting for a crisis to force the decision.</p>

