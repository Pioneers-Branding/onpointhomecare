          <h2 id="hidden-costs">Hidden Costs Worth Asking About</h2>
          <p>Beyond the headline hourly rate, a few line items can meaningfully change your actual monthly bill if you don't ask about them upfront. Minimum visit lengths are the most common: many agencies bill a two-hour minimum even for a shorter task, since a caregiver still has to travel to and from the visit. Statutory holidays and, in some cases, evening or overnight hours can carry a surcharge above the standard daytime rate. Mileage or travel time may be billed separately if your home is outside an agency's core service area. None of these are unreasonable, but they should appear clearly in a written agreement before you commit, not as a surprise on your first invoice.</p>

          <h2 id="agency-vs-independent">Agency Care vs. Hiring Independently</h2>
          <p>Some families consider hiring a caregiver directly, outside of an agency, as a way to reduce the hourly rate. It's true that an independent caregiver's rate is often lower than an agency's blended rate, since the agency's rate also covers recruitment, background checks, training, supervision, liability insurance, and backup coverage when a caregiver is sick or on vacation. Hiring independently shifts all of that responsibility, and the legal obligations of being an employer, onto the family. For many households, the peace of mind and continuity of an agency's screening, supervision, and backup staffing is worth the difference in price, particularly for families managing a complex or changing care need without the time to manage employment logistics themselves.</p>

          <h2 id="public-offset">How Public Programs Can Offset the Cost</h2>
          <p>Private home care isn't the only option on the table. BC residents may also qualify for publicly subsidized home support through their regional health authority, or for the CSIL program, which provides self-directed funding for people with high physical care needs to hire and manage their own support workers. Both require a clinical assessment and typically cover a narrower scope than a full private care plan, which is why many Metro Vancouver families end up combining subsidized hours with private care to fill the gaps. If eligible, you may also be able to offset part of your private home care spending through federal medical expense or disability-related tax credits, which are worth reviewing with a tax professional.</p>
          <p>The application process for either public program starts with a referral to your regional health authority's home and community care office, which can be initiated by a family doctor, a hospital social worker, or the family directly. It costs nothing to apply, and even a partial approval, say, a couple of subsidized visits a week, can meaningfully reduce what a family needs to budget for privately.</p>

          <h2 id="getting-accurate-quote">How to Get an Accurate Quote</h2>
          <p>The fastest way to move from a general price range to a real number is a free in-home <a href="care-assessment">care assessment</a>. Our Lead Registered Nurse will review your parent's specific needs, current health status, and home environment, then put together a written care plan with transparent hourly pricing, so you can compare it honestly against other options and your household budget.</p>
          <p>When you do compare quotes between agencies, ask each one the same set of questions: what is included in the hourly rate, is there a minimum visit length, how are evenings, weekends, and holidays billed, and what happens if your regular caregiver is unavailable. Agencies that answer these clearly and in writing, rather than vaguely, tend to be the ones that avoid billing surprises down the road. A price that looks lower on the surface can end up costing more once minimum visit fees, surcharges, or backup staffing gaps are factored in.</p>

