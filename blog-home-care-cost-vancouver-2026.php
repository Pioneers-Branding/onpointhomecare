          <h2 id="monthly-costs">Estimating Monthly Costs</h2>
          <p>Once you know the hourly range for the type of care you need, monthly cost is mostly a function of how many hours per week you book. A few illustrative examples, using a mid-range hourly rate as a planning estimate:</p>
          <p>A few hours of companion or personal care a couple of times a week, often used for light support and family respite, generally lands in the low hundreds of dollars monthly. Daily visits of one to two hours for personal care support typically move into the low-to-mid thousands per month. Longer daily blocks, such as four to eight hours a day, push costs into the mid-thousands and up, since the total hours booked each month rise substantially.</p>
          <p>These are planning ranges, not quotes. The only way to get an accurate number for your specific situation is a written estimate based on an actual care plan, which is exactly what a <a href="services">care assessment</a> is designed to produce.</p>
          <p>It also helps to think in terms of hours per week rather than hours per day when budgeting, since that's usually how agencies calculate a monthly estimate. Two hours a day, five days a week, works out to roughly 40 hours a month, while the same two hours delivered daily, seven days a week, is closer to 60 hours. That difference alone can shift a monthly estimate by hundreds of dollars, which is why it's worth being specific about which days you actually need coverage before comparing quotes between agencies.</p>

          <h2 id="24-hour-costs">24-Hour and Live-In Care Costs</h2>
          <p>Round-the-clock support is priced very differently from scheduled hourly visits, and the two most common models, live-in care and 24-hour shift care, are not the same thing. Live-in care generally uses one caregiver who resides in the home and is available overnight but sleeps for a portion of the night, billed at a flat daily rate. 24-hour shift care uses multiple caregivers rotating in shifts so that someone is awake and actively monitoring around the clock, which requires more staffing hours and therefore costs meaningfully more per month than live-in care.</p>
          <p>Because the staffing model, not just the hours, drives the price difference between these two options, it's worth having an honest conversation with your care coordinator about which one your parent's actual overnight needs require, rather than assuming round-the-clock always means the same thing.</p>

          <h3>Three Common Care Scenarios</h3>
          <p>To make these ranges more concrete, here is how cost typically scales across three situations we see often in Metro Vancouver:</p>
          <p><strong>Light daytime support:</strong> A parent who is largely independent but needs help with a shower a few times a week, meal prep, and occasional errands. This usually means a handful of hours weekly and sits at the lower end of the monthly cost spectrum.</p>
          <p><strong>Daily personal care:</strong> A parent recovering from a fall or managing a chronic condition, needing one to two hours of personal care support every day, plus occasional companionship. This moves into a mid-range monthly cost, since the hours add up daily rather than a few times a week.</p>
          <p><strong>Around-the-clock supervision:</strong> A parent with advanced dementia or a high fall risk who cannot safely be left alone, requiring either live-in or full 24-hour shift coverage. This represents the highest monthly cost tier, for the staffing reasons outlined above.</p>
          <p>Where your family lands on this spectrum, and how it shifts over time, is exactly what a proper assessment is meant to clarify.</p>

          <h2 id="price-factors">What Actually Moves Your Price</h2>
          <p>A handful of factors explain most of the variation you'll see between quotes:</p>
          <p><strong>Level of care needed.</strong> Skilled nursing tasks cost more than companionship, as outlined above.</p>
          <p><strong>Hours and consistency.</strong> Booking more hours per week, or a longer-term commitment, sometimes lowers the effective hourly rate, while short, sporadic bookings often carry a premium.</p>
          <p><strong>Time of day.</strong> Evening, overnight, and weekend or holiday shifts frequently carry higher rates than weekday daytime visits, reflecting caregiver availability and demand.</p>
          <p><strong>Caregiver qualifications.</strong> A Health Care Aide, Licensed Practical Nurse, and Registered Nurse each bring a different scope of practice and a different price point.</p>
          <p><strong>Complexity of the care plan.</strong> Managing multiple chronic conditions, mobility equipment, or specialized dietary needs can increase both the time required per visit and the level of caregiver needed.</p>

