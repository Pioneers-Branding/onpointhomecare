      <p class="text-paragraph">Surrey Memorial Hospital, located at 13750 96 Avenue, is a major Fraser Health acute care and trauma centre serving Surrey and much of the surrounding Fraser Valley. In South Surrey and White Rock, Peace Arch Hospital is the local acute care facility, providing emergency and surgical services closer to that part of the city. Because these two hospitals serve different parts of Surrey, the practical distance from home to hospital, and back home again after discharge, varies significantly depending on where in the city your parent lives.</p>
