          <h2 id="disability-tax-credit">The Disability Tax Credit</h2>
          <p>The Disability Tax Credit, often called the DTC, is a separate non-refundable credit for individuals with a severe and prolonged impairment in physical or mental function that markedly restricts daily living, certified by a qualified medical practitioner on Form T2201. Approval doesn't pay for home care directly, but it can meaningfully reduce the family's overall tax bill, and if the person with the impairment doesn't need the full credit themselves, it can often be transferred to a supporting spouse or family member.</p>
          <p>Because approval for the DTC can also affect eligibility for related programs and credits, including aspects of the Canada Caregiver Credit, it's often worth applying even if you're unsure whether your parent will "need" the credit directly. It establishes documentation that can matter later.</p>

          <h2 id="caregiver-credit">The Canada Caregiver Credit</h2>
          <p>The Canada Caregiver Credit is a non-refundable federal credit available to people financially supporting a spouse, common-law partner, or dependant with a physical or mental impairment. The amount you can claim depends on your relationship to the dependant and is gradually reduced as the dependant's own net income rises above a threshold the CRA sets each year, reaching zero once income passes a higher indexed amount.</p>
          <p>This credit is assessed separately from the Disability Tax Credit and the Medical Expense Tax Credit, and in some cases a family may be able to claim more than one, so it's worth reviewing all three together with a tax professional rather than assuming only one applies.</p>

          <div class="quote-card-teal">
            <strong>From our clinical experience:</strong> Families are often surprised that applying for the Disability Tax Credit and organizing attendant care receipts throughout the year, not just at tax time, makes the biggest practical difference. Waiting until April to reconstruct a year of caregiving expenses is where most missed claims happen.
          </div>

          <h2 id="other-supports">Other Supports Worth Knowing About</h2>
          <p>Beyond federal tax credits, BC families should also be aware of the Home Adaptations for Independence program, which provides financial assistance for home modifications like grab bars, ramps, and walk-in showers that support aging in place. It's a separate program from tax credits, administered provincially, and worth exploring alongside your tax planning if your parent's home needs safety modifications to support ongoing <a href="home-care-cost">home care</a>.</p>
          <p>It's also worth checking for provincial credits that sometimes overlap with home care costs, such as home renovation tax credits for seniors or persons with disabilities, which some provinces offer separately from federal programs. Availability and rules vary, so this is another area where a quick call to an accountant familiar with BC returns can surface a credit you didn't know existed.</p>

          <h2 id="common-mistakes">Common Mistakes Families Make</h2>
          <p>A few patterns come up again and again in conversations with families after tax season has already passed. The most common is not applying for the Disability Tax Credit at all, often because a family assumes their parent's condition "isn't severe enough" without ever having a medical practitioner formally assess it against the CRA's criteria. Another is treating a private home care invoice as fully claimable without separating out the portion that reflects eligible attendant care wages from administrative or booking fees, which can result in an inflated claim that gets adjusted by the CRA later. A third is waiting until the return is due to gather a year's worth of receipts, which often means missing documentation that a caregiver or agency can no longer easily reproduce.</p>

          <h2 id="documentation">Documentation That Actually Matters</h2>
          <p>Whichever credits apply to your situation, the CRA generally expects clear supporting documentation: receipts that name the payee and, for an individual caregiver, their social insurance number; a signed letter or certification from a medical practitioner confirming the need for attendant care where required; and, if care was provided through a facility or agency, an itemized breakdown separating eligible wages from non-eligible costs. Keeping this paperwork organized throughout the year, rather than reconstructing it in April, is the single biggest factor in whether a claim goes smoothly.</p>

          <h2 id="getting-it-right">Getting It Right</h2>
          <p>None of this is a substitute for professional tax advice, and we are not tax advisors. What we can tell you, from supporting hundreds of Metro Vancouver families through paid home care, is that the credits above are real, they do add up, and the families who benefit most are the ones who talk to an accountant or the CRA directly about their specific situation before filing, rather than assuming home care costs simply aren't deductible.</p>

