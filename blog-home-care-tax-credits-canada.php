        <div class="article-body">
          <p>Tax season is when a lot of families realize, often too late, that they've been paying for care at home all year without keeping the records that would have made part of it deductible. The question of a <strong>home care tax credit in Canada</strong> comes up constantly in our conversations with families, and the honest answer is that there isn't one single "home care credit." Instead, there are several federal credits that can apply depending on who is receiving care, who is paying for it, and what kind of care it is.</p>
          <p>This is general information, not tax advice. Rules, dollar thresholds, and annual limits are set by the Canada Revenue Agency and are indexed or updated over time, so we strongly recommend confirming current figures with the CRA directly or with a tax professional before you file.</p>

          <h2 id="quick-answer">The Quick Answer</h2>
          <p>Most families paying for home care in Canada can potentially claim eligible attendant care wages under the Medical Expense Tax Credit. If the person receiving care has a severe and prolonged impairment, the Disability Tax Credit may also apply, and the Canada Caregiver Credit can provide additional relief for the person supporting them financially. These credits can sometimes be combined, but each has its own eligibility rules and paperwork, so it's worth understanding all three before assuming you don't qualify.</p>

          <h2 id="medical-expense-credit">The Medical Expense Tax Credit</h2>
          <p>The Medical Expense Tax Credit is a non-refundable federal credit that applies to eligible medical expenses, including certain attendant care costs, above a minimum threshold. That threshold is generally the lesser of a set percentage of net income or a fixed dollar amount that the CRA adjusts annually, so it's worth checking the current year's threshold on the CRA website rather than relying on last year's figure.</p>
          <p>Attendant care wages can qualify when the care is provided by someone other than your spouse or common-law partner, is at least 18 years old, and delivers eligible personal support such as bathing, dressing, feeding, or mobility assistance. The CRA recognizes wages paid to registered nurses, licensed practical nurses, certified health care aides, and personal support workers as eligible attendant care. Housekeeping tied directly to the person's care, meal preparation, and certain transportation costs connected to care may also qualify, but rent, general food costs, and administrative fees generally do not.</p>
          <p>Some families choose to claim attendant care as a medical expense even while also claiming the Disability Tax Credit for the same person. There are annual limits on how much part-time attendant care can be claimed this way, and those limits can change from year to year, so confirm the current cap with the CRA or your accountant rather than relying on a figure you saw online.</p>
          <p>The claim also depends on who paid, and for whom. You can generally claim eligible medical expenses paid for yourself, your spouse or common-law partner, or a dependant, provided you keep the receipts in your own name as the payer. If care costs are split between siblings supporting the same parent, only the person who actually paid a given expense can typically claim it, so families often find it simpler to designate one person as the payer of record and reimburse each other separately, rather than trying to split individual receipts.</p>

