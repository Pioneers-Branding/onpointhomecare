        <div class="section-tag">The Service in Detail</div>
        <h2 class="section-heading">What Respite Care Actually Involves</h2>
        <p class="section-subheading">Respite is arranged around what the carer needs to be free to do, and around keeping the cared-for person's routine intact while they are away.</p>
      </div>
      <div class="svc-longform">
        <div class="svc-block">
          <span class="svc-block-num">Component 01</span>
          <h3>Planned Regular Respite</h3>
          <p>The most effective respite is booked in advance and happens every week, whether or not it feels needed that particular week. A fixed afternoon or a regular overnight is far more protective than an emergency break taken once things have already broken down.</p>
          <p>Regular cover also means the substitute carer becomes familiar. The client is not being handed to a stranger at a moment of stress; they are being handed to somebody they already know, which removes most of the resistance families expect.</p>
          <ul class="svc-block-list">
            <li>A recurring weekly or fortnightly slot</li>
            <li>The same aide wherever possible</li>
            <li>Predictable cover the carer can plan around</li>
            <li>Day, evening or overnight sessions</li>
            <li>Gradual introduction before the first full session</li>
            <li>Reviewed as the caring situation changes</li>
          </ul>
        </div>
        <div class="svc-block">
          <span class="svc-block-num">Component 02</span>
          <h3>Extended Respite for Holidays and Absences</h3>
          <p>Longer cover &mdash; a week, a fortnight, occasionally more &mdash; so that a carer can take a holiday, travel for a family event, or have their own operation without cancelling it for the third time.</p>
          <p>Extended respite needs proper planning: a detailed handover of routines, preferences, medications and warning signs, and enough overlap beforehand that the substitute carer is genuinely up to speed rather than working from a sheet of paper.</p>
          <ul class="svc-block-list">
            <li>Cover for holidays and family events</li>
            <li>Support during the carer's own illness or surgery</li>
            <li>Detailed written handover of routines and preferences</li>
            <li>Overlap visits before the carer leaves</li>
            <li>Daily updates to the carer while away</li>
            <li>Nursing support alongside where clinical needs exist</li>
          </ul>
        </div>
        <div class="svc-block">
          <span class="svc-block-num">Component 03</span>
          <h3>Emergency and Short-Notice Cover</h3>
          <p>Sometimes there is no planning. A carer is admitted to hospital, injured, bereaved, or simply reaches a point where they cannot continue that day.</p>
          <p>We cannot promise instant availability &mdash; nobody honestly can &mdash; but we treat these calls as urgent, and we will tell you quickly and plainly what we can put in place and when, rather than leaving you waiting on a maybe.</p>
          <ul class="svc-block-list">
            <li>Urgent response to carer illness or injury</li>
            <li>Cover following a carer's hospital admission</li>
            <li>Support during family crisis or bereavement</li>
            <li>Rapid assessment where care needs are unknown to us</li>
            <li>Honest, immediate answers on availability</li>
            <li>Bridging cover while longer arrangements are made</li>
          </ul>
        </div>
        <div class="svc-block">
          <span class="svc-block-num">Component 04</span>
          <h3>Keeping the Routine Intact</h3>
          <p>The single biggest worry carers have about respite is that things will be done wrong and they will return to a mess &mdash; a distressed relative, a disrupted sleep pattern, medication confusion.</p>
          <p>We take the handover seriously for exactly that reason. What time they wake. What they eat and what they refuse. Which chair. Which programme. What settles them when they are agitated, and what makes it worse. A respite session that ignores all that is not a break; it is a problem waiting for the carer's return.</p>
          <ul class="svc-block-list">
            <li>Detailed routine and preference handover</li>
            <li>Continuity of mealtimes and sleep patterns</li>
            <li>Medication timing maintained exactly</li>
            <li>Familiar activities and settling techniques</li>
            <li>Written record of the whole period</li>
            <li>Full handover back on the carer's return</li>
          </ul>
        </div>
        <div class="svc-block">
          <span class="svc-block-num">Component 05</span>
          <h3>Respite Where Clinical Needs Exist</h3>
          <p>Many carers are doing genuinely clinical work &mdash; wound dressings, catheter care, complex medication, repositioning through the night. Respite for those families needs nursing, not a sitter.</p>
          <p>Where that is the case, our nursing team provides the cover so the carer can step away without leaving clinical tasks to someone unqualified or, more commonly, doing them at a distance by phone.</p>
          <ul class="svc-block-list">
            <li>Registered nursing cover where clinical needs exist</li>
            <li>Medication administration during the respite period</li>
            <li>Wound, catheter and continence care</li>
            <li>Overnight repositioning and pressure care</li>
            <li>Documented clinical record for the period</li>
            <li>Escalation pathway agreed before the carer leaves</li>
          </ul>
        </div>
        <div class="svc-block">
          <span class="svc-block-num">Component 06</span>
          <h3>Support for the Carer Themselves</h3>
          <p>Part of what we do is aimed at the carer rather than the client. That means being honest about what is sustainable, pointing out when an arrangement has stopped being viable, and knowing what local support exists.</p>
          <p>Many carers have never been asked how they are doing. Asking, and taking the answer seriously, is a legitimate part of this service.</p>
          <ul class="svc-block-list">
            <li>Honest conversations about sustainability</li>
            <li>Practical guidance on safe moving and handling</li>
            <li>Signposting to local carer support</li>
            <li>Advice on planning ahead rather than reacting</li>
            <li>Regular review of whether the cover is enough</li>
            <li>Support with decisions about future care</li>
          </ul>
        </div>
      </div>

