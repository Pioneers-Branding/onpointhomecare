          <h2 id="costs">What Home Care Costs in Burnaby</h2>
          <p>Home care in Burnaby is generally priced hourly, with cost driven by weekly hours needed and the level of care required, whether that's a caregiver, a Licensed Practical Nurse, or a Registered Nurse. A few hours of weekly companion care is considerably less than full-time nursing support, and many families begin with a smaller number of hours and adjust as circumstances change. Our <a href="home-care-cost">home care cost guide</a> explains the main pricing factors, while a free in-home assessment gives you a precise number based on your parent's actual needs.</p>

          <h2 id="getting-started">How to Get Started</h2>
          <p>Starting home care in Burnaby follows the same three steps wherever in the city you live: an initial conversation about what's changed, an in-home assessment covering safety and medical needs, and a care plan matched with a caregiver already familiar with your part of the city, whether that's a Brentwood tower or an Edmonds bungalow.</p>
          <p>If you're ready to talk it through, reach out through our <a href="contact">contact page</a>, or request a free <a href="care-assessment">in-home care assessment</a> to build a plan specific to your family's needs in Burnaby.</p>

