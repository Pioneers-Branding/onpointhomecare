          <h2 id="healthcare">Burnaby Hospital and Discharge Planning</h2>
          <p><strong>Burnaby Hospital</strong>, located at 3935 Kincaid Street, is the city's main acute care facility and the hospital most Burnaby families deal with for emergencies, surgeries, and discharge planning. As with any hospital transition, the days immediately after coming home are often when families feel least prepared, particularly around new medications, mobility restrictions, or wound care instructions that were explained quickly at discharge.</p>
          <p>Our <a href="hospital-to-home-care">hospital-to-home care</a> and <a href="post-discharge-nursing">post-discharge nursing</a> services are designed to close that gap, getting a caregiver or nurse into the home soon after a Burnaby Hospital discharge to support recovery and reduce the risk of a return trip to the ER.</p>
          <p>Burnaby's location between Vancouver and New Westminster also means some residents, particularly in Edmonds or near the Boundary Road border, may see specialists or attend follow-up appointments outside Burnaby itself. A caregiver who understands the wider road network, including the Lougheed Highway and the connections to Highway 1, can make those cross-city appointments far less stressful to coordinate.</p>

          <h2 id="services">Home Care Services Available in Burnaby</h2>
          <p>Home care needs vary widely, from occasional companionship to continuous nursing supervision, and the right level depends on your loved one's health and safety. Services Burnaby families frequently request include:</p>
          <ul>
            <li><a href="personal-care">Personal care</a>: bathing, dressing, and hygiene support delivered with patience and dignity.</li>
            <li><a href="companion-care">Companion care</a>: company, light housekeeping, meal preparation, and transportation around Burnaby.</li>
            <li><a href="dementia-care">Dementia care</a>: structured daily routines and safety supervision for clients with memory loss.</li>
            <li><a href="wound-care">Wound care</a> and <a href="post-operative-care">post-operative care</a>: nursing support for clients recovering from surgery or injury.</li>
            <li><a href="24-hour-home-care">24-hour home care</a>: continuous support for clients who are unsafe living alone.</li>
            <li><a href="respite-care">Respite care</a>: short-term relief for family caregivers who need a break.</li>
          </ul>
          <p>Every care plan should be based on a clinical assessment rather than a fixed package, since needs in a Metrotown high-rise can look very different from needs on a Deer Lake acreage. Our full <a href="services">home care services</a> page outlines everything we offer if you'd like to explore options in more depth.</p>

          <div class="quote-card-teal">
