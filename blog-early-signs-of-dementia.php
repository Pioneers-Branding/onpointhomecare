        <div class="article-body">
          <p>When a parent starts repeating themselves or loses their train of thought, it's tempting to explain it away: a bad night's sleep, a distracting week, "just getting older." Sometimes that's exactly what it is. But dementia rarely announces itself with a single dramatic moment. It shows up first in small inconsistencies that, taken together, tell a different story.</p>
          <p>As a Registered Nurse who has assessed hundreds of families across Metro Vancouver, I've found that the families who cope best are the ones who noticed the early signs of dementia and acted on them calmly, long before a crisis forced the decision. Here are the ten changes worth paying attention to.</p>

          <h2 id="memory-lapses">1. Memory Lapses That Disrupt Daily Life</h2>
          <p>Everyone forgets a name occasionally. The difference with dementia is that the memory loss interferes with daily function: asking the same question five times in an hour, forgetting a recently learned piece of information, or relying heavily on notes and reminders for things that used to come naturally.</p>

          <h2 id="planning">2. Difficulty Planning or Solving Problems</h2>
          <p>Watch for changes in how someone manages a multi-step process they've handled for years: following a familiar recipe, balancing a checkbook, or keeping track of monthly bills. Tasks that require concentration and sequencing often become noticeably harder before memory loss itself is obvious.</p>

          <h2 id="time-place">3. Confusion With Time or Place</h2>
          <p>Losing track of dates, seasons, or the passage of time is common. More concerning is genuine disorientation: forgetting how they got somewhere, or not recognizing a familiar neighborhood they've lived in for decades.</p>

          <h2 id="familiar-tasks">4. Trouble With Familiar Tasks</h2>
          <p>Difficulty completing everyday tasks at home, at work, or during leisure activities: forgetting the rules of a lifelong card game, or struggling to operate the TV remote or the washing machine they've used for twenty years.</p>

          <div class="article-callout">
            <div class="article-callout-title">
              <svg class="icon-sm" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2"><circle cx="12" cy="12" r="10"></circle><line x1="12" y1="16" x2="12" y2="12"></line><line x1="12" y1="8" x2="12.01" y2="8"></line></svg>
              Clinical Tip
            </div>
            <p>Keep a simple written log of specific incidents: the date, what happened, and how it differed from normal. A concrete list of examples is far more useful to a family doctor than "she's been more forgetful lately."</p>
          </div>

          <h2 id="language">5. Language and Word-Finding Problems</h2>
          <p>Struggling to follow or join a conversation, stopping mid-sentence with no idea how to continue, or repeatedly substituting an unusual word for the correct one, calling a "watch" a "hand-clock," for example.</p>

          <h2 id="misplacing">6. Misplacing Things and Losing the Ability to Retrace Steps</h2>
          <p>Everyone misplaces items now and then. A warning sign is putting things in unusual places, such as keys in the fridge or a wallet in the laundry hamper, and being unable to retrace steps to find them, sometimes accusing others of taking the item.</p>

          <h2 id="judgment">7. Poor or Decreased Judgment</h2>
          <p>Changes in judgment or decision-making, particularly around money and personal care: giving unusually large amounts to telemarketers, wearing clothing inappropriate for the weather, or a noticeable decline in grooming and hygiene.</p>

          <h2 id="withdrawal">8. Withdrawal From Work or Social Activities</h2>
          <p>A person may start to withdraw from hobbies, social engagements, or family gatherings because they've become aware, even if they don't say so, that they can no longer keep up with conversations or activities the way they used to.</p>

          <h2 id="mood">9. Changes in Mood and Personality</h2>
          <p>Confusion, suspicion, depression, anxiety, or increased irritability, especially in unfamiliar settings or when a routine is disrupted. A normally easygoing parent becoming uncharacteristically anxious or short-tempered is often one of the earliest signs family members notice, even before memory changes.</p>

          <div class="quote-card-teal">
            <strong>From our clinical experience:</strong> Mood and personality changes are frequently dismissed as "just stress" or "getting grumpier with age," but they're often the very first sign a family notices, sometimes months before memory problems become obvious.
          </div>

          <h2 id="next-steps">10. When to Seek a Professional Assessment</h2>
          <p>Noticing one or two of these signs occasionally isn't cause for alarm, but a pattern of several, persisting over weeks or months, is worth discussing with a physician. Many treatable conditions (urinary tract infections, thyroid imbalances, medication side effects, depression, vitamin B12 deficiency) can mimic dementia symptoms, so a proper medical evaluation is the essential next step, not a diagnosis you make at home.</p>
          <p>If the assessment does point toward dementia, an early diagnosis gives your family more time to plan, legally, financially, and practically, while your parent can still take part in those decisions. It also opens the door to <a href="dementia-care">structured dementia care</a> that keeps daily routines calm and familiar for as long as possible.</p>

