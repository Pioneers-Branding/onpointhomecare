        <div class="article-body">
          <p>A parent who lives alone can go an entire day, sometimes several, without a real conversation. The phone rings less than it used to. Friends have moved away, passed on, or stopped driving at night. For many families in Metro Vancouver, this quiet decline is harder to spot than a physical health problem, because nothing looks urgent from the outside. <strong>Companion care for seniors</strong> in Vancouver exists specifically to fill that gap: regular, reliable human connection built into the week, not left to chance.</p>
          <p>This isn't about medical treatment or hands-on personal care. It's about restoring the ordinary rhythm of daily life, someone to share a cup of tea with, talk through the news, or simply notice if something seems off. As a nurse who has watched isolation quietly erode a senior's health long before any diagnosis appears, I want to walk through what companion care actually looks like and how to recognize when a parent needs it.</p>

          <h2 id="what-is-companion-care">What Companion Care Actually Is</h2>
          <p>Companion care is non-medical support focused on social connection and everyday assistance rather than clinical tasks. A companion caregiver visits on a set schedule to talk, share meals, accompany a senior on errands or appointments, encourage light activity, and help with simple tasks like tidying up or preparing a snack. It's the lightest level of home support, designed for seniors who are largely capable but who are isolated, bored, or simply need a friendly presence built into their week.</p>
          <p>It's worth being clear about what companion care is not. It does not include bathing, dressing, medication administration, or wound care, those fall under <a href="personal-care">personal care</a> or nursing services. If your parent needs a hand with daily living tasks in addition to company, our <a href="companion-care">companion care program</a> can be paired with other levels of support as needs change.</p>

          <h2 id="loneliness-is-serious">Why Loneliness Is a Health Issue, Not Just a Feeling</h2>
          <p>It's tempting to treat loneliness as an emotional inconvenience rather than a health concern, but the research says otherwise. Chronic loneliness in older adults has been linked to a higher risk of depression, anxiety, cognitive decline, and cardiovascular problems. Isolated seniors are also more likely to neglect meals, skip medications, and stop moving around as much, all of which compound existing health risks. Roughly one in four seniors living in the community report feeling lonely on a regular basis, and the number climbs sharply for those who live alone or have outlived a spouse.</p>
