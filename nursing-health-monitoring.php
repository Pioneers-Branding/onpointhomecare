      <div class="faq-accordion-container">
        <div class="faq-item active">
          <button class="faq-trigger" onclick="toggleFaq(this)">
            <span class="faq-q-text">How is this different from a family member checking blood pressure at home?</span>
            <span class="faq-q-icon">+</span>
          </button>
          <div class="faq-content">
            <p>The measurements themselves may be similar. What differs is consistency of technique, clinical interpretation of what the numbers mean in context, and a written record that a physician can actually use. A nurse also notices the things that are not being measured &mdash; a change in gait, a swollen ankle, confusion that was not there last month.</p>
          </div>
        </div>
        <div class="faq-item">
          <button class="faq-trigger" onclick="toggleFaq(this)">
            <span class="faq-q-text">How often should monitoring visits happen?</span>
            <span class="faq-q-icon">+</span>
          </button>
          <div class="faq-content">
            <p>It depends on how stable the conditions are. Something newly diagnosed or recently changed may warrant weekly visits; a well-controlled long-term condition may only need monthly. The interval is set at the assessment and adjusted as the picture changes.</p>
          </div>
        </div>
        <div class="faq-item">
          <button class="faq-trigger" onclick="toggleFaq(this)">
            <span class="faq-q-text">Do you share the results with our family doctor?</span>
            <span class="faq-q-icon">+</span>
          </button>
          <div class="faq-content">
            <p>Yes, with your consent. Written summaries are the point of the exercise &mdash; they give the physician real between-appointment data instead of a recollection of how the last few weeks felt. Families receive the same information.</p>
          </div>
        </div>
        <div class="faq-item">
          <button class="faq-trigger" onclick="toggleFaq(this)">
            <span class="faq-q-text">What happens if a reading is abnormal?</span>
            <span class="faq-q-icon">+</span>
          </button>
          <div class="faq-content">
            <p>The nurse assesses it in context rather than reacting to a single number, escalates to the treating physician where the care plan calls for it, and tells the family what was found and what was done. Where a reading indicates an emergency, they act on it immediately.</p>
          </div>
        </div>
        <div class="faq-item">
          <button class="faq-trigger" onclick="toggleFaq(this)">
            <span class="faq-q-text">Is this worth arranging if there is no diagnosed condition yet?</span>
            <span class="faq-q-icon">+</span>
          </button>
          <div class="faq-content">
            <p>Sometimes, yes &mdash; particularly where a family has a persistent sense that something is changing but cannot point to what. A documented baseline now is what makes it possible to prove or rule out a decline six months from now, and that evidence is genuinely useful to a physician.</p>
          </div>
        </div>
