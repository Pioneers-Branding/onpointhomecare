        <div class="section-tag">The Service in Detail</div>
        <h2 class="section-heading">What Nursing &amp; Health Monitoring Actually Involves</h2>
        <p class="section-subheading">The service is deliberately systematic. Its value comes from doing the same thing carefully and repeatedly.</p>
      </div>
      <div class="svc-longform">
        <div class="svc-block">
          <span class="svc-block-num">Component 01</span>
          <h3>Establishing a Clinical Baseline</h3>
          <p>The first visit is longer than the rest, because everything afterwards is measured against it. We record vital signs, weight, mobility, cognition, appetite, continence, skin condition, pain and mood &mdash; and we ask the family what normal looks like for this person.</p>
          <p>Normal is individual. A blood pressure that would concern us in one client is unremarkable in another. A person who has always eaten little is different from one whose appetite has halved. Without that starting point, later readings are just numbers without meaning.</p>
          <ul class="svc-block-list">
            <li>Full baseline clinical assessment</li>
            <li>Documented starting measurements</li>
            <li>Family account of the person's usual state</li>
            <li>Review of existing diagnoses and medications</li>
            <li>Identification of the specific markers to track</li>
            <li>Agreement on visit frequency and reporting</li>
          </ul>
        </div>
        <div class="svc-block">
          <span class="svc-block-num">Component 02</span>
          <h3>Vital Signs and Physical Measurements</h3>
          <p>At each visit the same observations are taken, using the same technique, and recorded. Blood pressure, pulse, temperature, oxygen saturation, blood glucose and weight, as the conditions being managed require.</p>
          <p>Technique consistency matters more than most people realise. A blood pressure taken standing, after the person has just walked from another room, is not comparable to one taken seated after five minutes' rest &mdash; and a spurious trend is worse than no trend at all.</p>
          <ul class="svc-block-list">
            <li>Blood pressure and pulse</li>
            <li>Temperature and oxygen saturation</li>
            <li>Blood glucose where relevant</li>
            <li>Weight and, where appropriate, fluid balance</li>
            <li>Respiratory rate and effort</li>
            <li>Pain assessment and scoring</li>
          </ul>
        </div>
        <div class="svc-block">
          <span class="svc-block-num">Component 03</span>
          <h3>Chronic Disease Surveillance</h3>
          <p>Each long-term condition has its own warning signs, and monitoring is targeted accordingly rather than applied identically to everyone.</p>
          <p>For heart failure that means weight, breathlessness and ankle swelling. For COPD it means oxygen saturation, sputum and exacerbation frequency. For diabetes it means glucose patterns and foot inspection. For hypertension it means the trend, not the individual reading.</p>
          <ul class="svc-block-list">
            <li>Condition-specific marker tracking</li>
            <li>Heart failure: weight, oedema, breathlessness</li>
            <li>COPD: saturation, sputum, exacerbation frequency</li>
            <li>Diabetes: glucose patterns and foot checks</li>
            <li>Kidney disease: fluid balance and symptoms</li>
            <li>Documented deterioration thresholds and actions</li>
          </ul>
        </div>
        <div class="svc-block">
          <span class="svc-block-num">Component 04</span>
          <h3>Medication Adherence and Effect Review</h3>
          <p>Prescribing assumes the medication is taken as directed. In practice, adherence in older adults is frequently imperfect &mdash; doses missed, doubled, stopped because of a side effect nobody was told about, or continued long after they should have ended.</p>
          <p>Our nurses check what is actually being taken, look at whether it appears to be working, watch for side effects, and report discrepancies to the prescriber. A blood pressure that will not come down is a different problem if the tablets are still in the packet.</p>
          <ul class="svc-block-list">
            <li>Review of what is actually being taken</li>
            <li>Dosette and blister pack checks</li>
            <li>Side effect identification and reporting</li>
            <li>Assessment of whether treatment appears effective</li>
            <li>Reconciliation after any prescribing change</li>
            <li>Direct communication with prescriber and pharmacy</li>
          </ul>
        </div>
        <div class="svc-block">
          <span class="svc-block-num">Component 05</span>
          <h3>Nutrition, Weight and Hydration</h3>
          <p>Unintentional weight loss, poor appetite and chronic mild dehydration are among the most under-recognised problems in older adults, and among the most consequential. Dehydration alone accounts for a substantial number of avoidable admissions.</p>
          <p>We weigh, we ask honestly about intake rather than accepting reassurance, and we look at the practical picture &mdash; what is in the fridge, whether cooking is still manageable, whether dentures fit, whether swallowing has changed.</p>
          <ul class="svc-block-list">
            <li>Regular weight measurement and trend tracking</li>
            <li>Food and fluid intake review</li>
            <li>Dehydration sign recognition</li>
            <li>Appetite and swallowing changes</li>
            <li>Practical review of shopping and cooking capacity</li>
            <li>Referral onward where intake is inadequate</li>
          </ul>
        </div>
        <div class="svc-block">
          <span class="svc-block-num">Component 06</span>
          <h3>Reporting to Families and Physicians</h3>
          <p>The record is the product. After each visit the family receives a written summary; with consent, so does the family physician.</p>
          <p>This is what turns monitoring from a reassurance exercise into something clinically useful. A physician with three months of recorded weights and blood pressures can make a decision. A physician with 'she's been a bit tired' cannot.</p>
          <ul class="svc-block-list">
            <li>Written summary after each visit</li>
            <li>Trend reporting rather than isolated readings</li>
            <li>Reports formatted for physician use</li>
            <li>Explicit flagging of concerning changes</li>
            <li>Escalation according to agreed thresholds</li>
            <li>Support for appointment preparation</li>
          </ul>
        </div>
      </div>

