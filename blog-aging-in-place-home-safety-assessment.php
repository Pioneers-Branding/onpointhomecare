          <h2 id="reassess">Signs It's Time to Reassess, Not Just Check Once</h2>
          <p>A handful of moments should prompt a fresh assessment even if the home was checked before. A recent fall, even a minor one, is one of the clearest signals, since falling once roughly doubles the likelihood of falling again. A hospital stay of any kind, a new mobility aid like a cane or walker, a noticeable change in vision, or the first signs of memory changes should all trigger a second look, because each of these shifts what "safe" actually means for that person. Even without any single triggering event, an annual review is a reasonable habit, since gradual decline is often invisible to people who see someone every day.</p>
          <p>Our <a href="blog-fall-prevention-checklist">home fall-prevention checklist</a> is a good starting point for the basics, and if a fall has already happened, our guide to <a href="blog-fall-recovery-first-30-days">fall recovery in the first 30 days</a> covers what should happen immediately afterward.</p>

          <h2 id="beyond-physical">Beyond Physical Hazards: Routine, Vision, and Cognition</h2>
          <p>A complete assessment looks past the physical structure of the home to how a person actually functions inside it. Are medications being taken correctly and on schedule? Is the person managing meals adequately, or has nutrition quietly declined? Are changes in memory affecting judgment around stove use, medication timing, or wandering at night? None of these show up on a basic hazard checklist, but each one materially changes how safe a home is for the person living in it. This is where a registered nurse's perspective adds something an environmental checklist alone cannot: connecting the physical space to the person's actual clinical picture.</p>

          <div class="quote-card-teal">
            <strong>From our clinical experience:</strong> The families who reach out to us after a fall almost always say the same thing: "We didn't think it was that bad yet." Aging rarely announces a single moment when a home stops being safe. It's a gradual mismatch, and the earlier you catch it, the more choices your family has.
          </div>

          <h2 id="who-does-it">Who Conducts an Assessment and What It Costs</h2>
          <p>Occupational therapists are the professionals most specifically trained in home modifications and adaptive equipment, and in British Columbia they're often required for accessing home adaptation rebate programs. Private occupational therapy assessments commonly range from roughly $170 to $400 depending on the scope of the visit and the report provided. A registered nurse-led assessment, like the ones our team conducts, looks at the home alongside the person's broader health picture, medications, mobility, cognition, and can help determine whether the next step is a home modification, a change in daily support, or both.</p>
          <p>Either way, it's worth asking upfront what the assessment includes, whether you'll receive a written report, and what qualifications the person conducting it holds.</p>

          <h2 id="modifications-vs-support">When Modifications Aren't Enough on Their Own</h2>
          <p>Grab bars, better lighting, and a decluttered hallway solve a real problem, but they don't address everything an assessment might uncover. Sometimes the honest conclusion is that the physical environment can be made safer, but the person also needs another set of hands nearby: help remembering medications, supervision around a stove that's become a genuine risk with early memory changes, or simply someone present during the hours a fall would otherwise go unnoticed. That's not a failure of the home. It's a normal part of how needs evolve, and it's worth discussing honestly rather than treating modifications as a complete solution on their own.</p>
          <p>Depending on what the assessment finds, that might mean a few hours of <a href="independent-home-care">light daily support</a> for someone who is largely independent, more structured <a href="home-nursing">home nursing</a> for a person managing a chronic condition alongside mobility changes, or overnight coverage if nighttime falls are the primary concern. The goal of pairing an assessment with the right level of support is the same as the goal of the home modifications themselves: more good years in the home your parent already knows.</p>

          <h2 id="building-a-plan">Turning an Assessment Into a Long-Term Plan</h2>
          <p>The real value of an assessment isn't the report itself, it's what your family does with it. Some recommendations are quick and low-cost: rearranging furniture, adding a night light, removing a rug. Others, like a bathroom renovation or moving a bedroom downstairs, take planning and budget, which is exactly why doing this proactively, rather than after a crisis, gives your family more options. For many families, the assessment also opens up a broader conversation about <a href="aging-in-place">aging in place</a> more generally, including whether some hands-on daily support would let a parent stay in their own home longer and more safely.</p>

