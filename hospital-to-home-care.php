          <ul class="svc-block-list">
            <li>Gentle physical transfer and settling into bed or armchair</li>
            <li>Full baseline vitals check (BP, SpO2, pulse, blood glucose, temperature)</li>
            <li>Pain assessment and immediate comfort measures</li>
            <li>Emotional reassurance and hydration check</li>
