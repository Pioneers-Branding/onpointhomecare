      <div class="section-header-center">
        <div class="section-tag">The Service in Detail</div>
        <h2 class="section-heading">What Palliative Care at Home Actually Involves</h2>
        <p class="section-subheading">Palliative nursing has two clients: the person being cared for, and the family around them. Both are part of the plan.</p>
      </div>
      <div class="svc-longform">
        <div class="svc-block">
          <span class="svc-block-num">Component 01</span>
          <h3>Pain and Symptom Management</h3>
          <p>Comfort is the first priority and the one everything else depends on. Pain that is not controlled overshadows everything &mdash; it prevents rest, prevents conversation, and is the thing families most fear witnessing.</p>
          <p>Our nurses assess pain and other symptoms systematically rather than by impression, administer the prescribed regimen, and give the palliative or prescribing team real information when medication needs adjusting. Symptoms beyond pain matter just as much: breathlessness, nausea, agitation, restlessness, dry mouth, constipation.</p>
          <p>Assessment continues throughout, because needs in palliative care change quickly and a regimen that was right last week may not be right today.</p>
          <ul class="svc-block-list">
            <li>Systematic pain assessment and scoring</li>
            <li>Administration of prescribed comfort medication</li>
            <li>Breathlessness and respiratory distress management</li>
            <li>Nausea, appetite and bowel symptom care</li>
            <li>Agitation and restlessness support</li>
            <li>Prompt liaison with prescribers for adjustment</li>
          </ul>
        </div>
        <div class="svc-block">
          <span class="svc-block-num">Component 02</span>
          <h3>Personal Care With Dignity</h3>
          <p>Washing, dressing, continence care and mouth care become harder as illness progresses, and they are frequently the aspect people find hardest to accept help with.</p>
          <p>How this is done matters as much as that it is done. Unhurried. Privately. Explaining before doing. Asking rather than instructing. Preserving as much of the person's own choice and modesty as their condition allows.</p>
          <p>For many families there is also relief in handing this over &mdash; being able to be a daughter or a husband again rather than the person who does the difficult and intimate tasks.</p>
          <ul class="svc-block-list">
            <li>Gentle, unhurried personal hygiene support</li>
            <li>Continence care with privacy preserved</li>
            <li>Mouth care and hydration comfort</li>
            <li>Repositioning for comfort and pressure relief</li>
            <li>Dressing and grooming as the person prefers</li>
            <li>Care delivered at the person's own pace</li>
          </ul>
        </div>
        <div class="svc-block">
          <span class="svc-block-num">Component 03</span>
          <h3>Comfort Measures and Skin Care</h3>
          <p>As mobility reduces, small physical measures become disproportionately important to comfort. Regular repositioning prevents pressure injuries that would cause real suffering. Mouth care relieves the dryness that is one of the most common sources of distress. Careful positioning eases breathlessness.</p>
          <p>These are unglamorous nursing tasks, and they are among the things that most reliably improve how someone's days feel.</p>
          <ul class="svc-block-list">
            <li>Regular repositioning for comfort and pressure relief</li>
            <li>Pressure injury prevention and management</li>
            <li>Frequent mouth and lip care</li>
            <li>Positioning to ease breathlessness</li>
            <li>Skin care and moisture management</li>
            <li>Comfort-focused equipment recommendations</li>
          </ul>
        </div>
        <div class="svc-block">
          <span class="svc-block-num">Component 04</span>
          <h3>Presence and Emotional Support</h3>
          <p>A great deal of palliative nursing is simply being there, calmly, without hurry. For the person, that means someone who is not frightened by the situation and is not going to rush the conversation. For the family, it means somebody in the house who knows what they are looking at.</p>
          <p>Our nurses are used to sitting with difficult questions, and used to answering them plainly. Vagueness is not kindness in this situation &mdash; families almost always cope better with honest information than with reassurance that does not match what they are seeing.</p>
          <ul class="svc-block-list">
            <li>Unhurried, calm presence</li>
            <li>Companionship for the person</li>
            <li>Space for family to be family</li>
            <li>Honest answers to difficult questions</li>
            <li>Support with anxiety and distress</li>
            <li>Respect for cultural, religious and personal wishes</li>
          </ul>
        </div>
        <div class="svc-block">
          <span class="svc-block-num">Component 05</span>
          <h3>Preparing and Guiding the Family</h3>
          <p>The questions families ask at two in the morning are rarely clinical. They are: is this normal, how long, what happens next, what do we do when it does, and am I doing this wrong.</p>
          <p>Part of our role is answering those before they become emergencies. That means explaining what changes to expect and roughly in what order, what does and does not warrant a call, what the medications are for, and what the practical steps are when the time comes.</p>
          <ul class="svc-block-list">
            <li>Explanation of what to expect as illness progresses</li>
            <li>Clear guidance on when to call and whom</li>
            <li>Explanation of medications and their purpose</li>
            <li>Practical preparation for the final period</li>
            <li>Support for family carers providing hands-on care</li>
            <li>Signposting to bereavement and community support</li>
          </ul>
        </div>
        <div class="svc-block">
          <span class="svc-block-num">Component 06</span>
          <h3>Working With Hospice and Palliative Teams</h3>
          <p>Where a hospice or specialist palliative team is involved, they lead the clinical direction and we carry it out at home, reporting back. Where they are not yet involved and we think they should be, we will say so.</p>
          <p>Coordination in this period is not administrative tidiness &mdash; it is what prevents a family being caught between services at the worst possible moment.</p>
          <ul class="svc-block-list">
            <li>Care delivered in line with the palliative plan</li>
            <li>Coordination with hospice and specialist teams</li>
            <li>Communication with the family physician</li>
            <li>Liaison over medication supply and equipment</li>
            <li>Referral onward where specialist input is needed</li>
            <li>Consistent documentation shared with the team</li>
          </ul>
        </div>
      </div>

