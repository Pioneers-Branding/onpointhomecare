        <div class="svc-block">
          <span class="svc-block-num">Stage 02</span>
          <h3>Bedside or In-Home RN Assessment</h3>
          <p>Our Lead Registered Nurse conducts a comprehensive clinical evaluation at the hospital bedside (VGH, St. Paul's, Richmond, Burnaby, Surrey Memorial) or patient's residence.</p>
          <ul class="svc-block-list">
            <li>Physical mobility, skin integrity, and cognitive baseline evaluation</li>
            <li>Discharge medication reconciliation and order translation</li>
            <li>Identification of required DME (hospital bed, lifts, commode, ramps)</li>
          </ul>
        </div>
        <div class="svc-block">
          <span class="svc-block-num">Stage 03</span>
          <h3>Care Plan Formulation &amp; Home Readiness</h3>
          <p>We build an individualized care protocol, deliver required medical equipment to the home, and assign a dedicated primary caregiver team.</p>
          <ul class="svc-block-list">
            <li>Tailored shift schedules (hourly, 12-hour, overnight, or 24/7)</li>
            <li>Caregiver chemistry and clinical skill matching</li>
            <li>Home environmental safety and fall hazard clearing</li>
          </ul>
        </div>
        <div class="svc-block">
          <span class="svc-block-num">Stage 04</span>
          <h3>Care Launch &amp; Closed-Loop Reporting</h3>
          <p>Care begins with doorstep reception. We initiate continuous clinical tracking and maintain direct progress reporting back to the primary care physician.</p>
          <ul class="svc-block-list">
            <li>First 48-hour intensive stabilization and vital sign surveillance</li>
            <li>Nursing progress summaries transmitted to physician clinics</li>
            <li>Scheduled 30/60/90-day reassessments with family and clinicians</li>
          </ul>
