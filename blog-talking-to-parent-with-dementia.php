        <div class="article-body">
          <p>You ask a simple question and get an answer that has nothing to do with what you asked. You explain something for the third time in ten minutes. You catch yourself getting short with the parent who used to be the most patient person you knew. If you're looking for practical ways on <strong>how to communicate with a parent with dementia</strong>, you're not failing at this, you're dealing with a genuinely different kind of conversation than the one you grew up having.</p>
          <p>Dementia changes how a person processes language, holds onto short-term information, and reads tone and body language. The good news is that communication with a parent who has dementia is a skill, and it responds to specific, learnable techniques. This guide walks through what actually helps, drawn from clinical best practice and the patterns our nursing team sees every day in homes across Metro Vancouver.</p>

          <h2 id="why-it-changes">Why Conversations Feel Different Now</h2>
          <p>Dementia affects the parts of the brain responsible for processing language, holding short-term memory, and following multi-step reasoning. Your parent isn't choosing to ignore you or being difficult on purpose. Word-finding becomes harder, following a long sentence becomes tiring, and a piece of information that felt obvious an hour ago may simply not be there anymore. Understanding this as a physical change, not a personality change or a lapse in effort, is the foundation for every technique below.</p>

          <h2 id="before-you-speak">Set the Scene Before You Speak</h2>
          <p>How you approach a conversation matters as much as what you say. Before you start talking, a few small adjustments make a real difference:</p>
          <ul>
            <li><strong>Reduce background noise.</strong> Turn off the television or radio so your parent isn't trying to filter your voice out of other sound.</li>
            <li><strong>Approach from the front.</strong> Coming up from behind or the side can startle someone with dementia. Walk into their line of sight first.</li>
            <li><strong>Get to eye level.</strong> Sit down if they're sitting. Standing over someone can unintentionally feel confrontational.</li>
            <li><strong>Say their name and yours.</strong> Starting with "Hi Mom, it's Sarah" orients them before you get into the content of the conversation.</li>
            <li><strong>Pick a good moment.</strong> If you know your parent is sharper in the morning or after a meal, save more involved conversations for that window.</li>
          </ul>

          <h2 id="how-to-talk">How to Communicate With a Parent With Dementia</h2>
          <p>Once the setting is right, a handful of speaking techniques consistently reduce frustration on both sides:</p>
          <ul>
            <li><strong>Use short, simple sentences.</strong> One idea per sentence is easier to process than a sentence with several clauses.</li>
            <li><strong>Offer limited choices, not open questions.</strong> "Would you like the soup or the sandwich?" is easier to answer than "What do you want for lunch?"</li>
            <li><strong>Slow your pace and pause.</strong> Give several extra seconds after you finish speaking before you assume they didn't understand.</li>
            <li><strong>Use a warm, matter-of-fact tone.</strong> People with dementia often pick up on emotional tone even when they've lost track of the words.</li>
            <li><strong>Repeat using the same words.</strong> If you need to repeat something, use the exact same phrasing rather than rewording it, which can be confusing.</li>
            <li><strong>Point and gesture.</strong> Pairing words with a gesture toward the object or place you mean reinforces the message.</li>
          </ul>

