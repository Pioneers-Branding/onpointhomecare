          <h2 id="daytime-strategies">Daytime Habits That Reduce Evening Agitation</h2>
          <p>Much of the most effective sundowning management happens hours before the symptoms actually appear. Strategies that tend to help include:</p>
          <ul>
            <li><strong>Get morning sunlight exposure.</strong> Natural light earlier in the day helps regulate the circadian rhythm.</li>
            <li><strong>Encourage physical activity during the day.</strong> A short walk or light exercise can reduce restlessness later and support better nighttime sleep.</li>
            <li><strong>Limit long daytime naps.</strong> Extended napping, especially in the late afternoon, can interfere with nighttime sleep and worsen the evening pattern.</li>
            <li><strong>Keep a consistent daily schedule.</strong> Predictable meal times, activity times, and rest times reduce the disorientation that can build toward evening.</li>
            <li><strong>Reduce caffeine after midday.</strong> Caffeine late in the day can interfere with the sleep needed to prevent next-day symptoms.</li>
          </ul>

          <h2 id="evening-strategies">Evening Strategies That Help in the Moment</h2>
          <p>Once late afternoon arrives, a calmer environment can reduce the intensity of symptoms:</p>
          <ul>
            <li><strong>Turn on lights before it gets dark.</strong> Reducing shadows and maintaining even lighting can prevent visual misinterpretation.</li>
            <li><strong>Lower the noise level.</strong> Turn off the television, quiet the household, and avoid scheduling visitors during this window if possible.</li>
            <li><strong>Offer a simple, calming activity.</strong> Folding towels, looking at photos, or listening to familiar music can redirect restless energy.</li>
            <li><strong>Stay calm yourself.</strong> A person with dementia often mirrors the emotional tone around them, so a steady, reassuring voice matters more than logical explanations.</li>
            <li><strong>Avoid arguing or reasoning.</strong> If your loved one is convinced of something untrue during an episode, redirecting gently tends to work better than correcting them.</li>
          </ul>

          <div class="quote-card-teal">
            <strong>From our clinical experience:</strong> Families often try to fix sundowning in the moment it's happening. The bigger wins usually come from what happens at 9am and 1pm, not 6pm. By the time the agitation starts, you're managing it, not preventing it.
          </div>

          <h2 id="when-to-call-doctor">When to Involve a Doctor</h2>
          <p>Contact your loved one's family doctor if sundowning episodes are severe, involve a risk of the person leaving the home unsafely, include new hallucinations, or don't respond at all to routine and environmental adjustments. A doctor can check for underlying infections or pain, review whether any current medications might be contributing, and, in some cases, discuss whether a short-term medication approach is appropriate. Medication is generally not the first-line response and is used selectively, alongside the non-drug strategies above rather than instead of them.</p>

          <h2 id="caregiver-toll">The Toll on Caregivers, and Why It's Worth Naming</h2>
          <p>Sundowning tends to hit right at the time of day caregivers are already the most tired, often after a full day of work, appointments, or other responsibilities. It's genuinely one of the harder parts of dementia caregiving, and it's reasonable to need a break from it, not just a strategy for surviving it. Many family caregivers describe the same pattern: they manage reasonably well during the calmer daytime hours, then feel their own patience wear thin right as their loved one's agitation is peaking, which is an exhausting combination to face day after day.</p>
          <p>Bringing in an evening caregiver even a few days a week through <a href="dementia-care">dementia home care</a> can give you back some of that window, whether that means starting dinner without interruption, taking a short walk to reset, or simply having backup during the hardest hour of the day. This isn't an admission that you can't handle it, it's a practical recognition that consistent evening support tends to produce calmer outcomes for everyone in the household, including the person living with dementia.</p>

