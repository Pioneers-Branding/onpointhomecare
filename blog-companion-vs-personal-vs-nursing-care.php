        <div class="article-body">
          <p>"Home care" gets used as if it's one thing, but it isn't. A family searching for help for an aging parent will quickly run into three very different terms, companion care, personal care, and nursing care, often used loosely and sometimes interchangeably by providers who should know better. The comparison of <strong>companion care vs personal care</strong> and nursing care matters because these three levels differ in training required, the tasks a caregiver is legally allowed to perform, and the hourly cost. Picking the wrong one means either paying for clinical expertise you don't need, or leaving a genuine medical need unmet.</p>
          <p>This guide breaks down what each level actually includes, what it costs in Metro Vancouver, and how to figure out which one fits your parent's situation right now, recognizing that the right answer often changes over time.</p>

          <h2 id="quick-comparison">Quick Comparison at a Glance</h2>
          <ul>
            <li><strong>Companion care:</strong> Social support, light housekeeping, errands, transportation. No hands-on physical assistance. No formal medical training required.</li>
            <li><strong>Personal care:</strong> Hands-on help with activities of daily living, bathing, dressing, toileting, mobility, alongside companion-level tasks. Provided by trained caregivers such as home health aides.</li>
            <li><strong>Nursing care:</strong> Clinical services, medication management, wound care, health monitoring, chronic disease management. Delivered or supervised by a Registered Nurse or Licensed Practical Nurse.</li>
          </ul>

          <h2 id="companion-care">Companion Care: Social Support and Everyday Help</h2>
          <p>Companion care is the lightest level of home support. It's built around social connection and everyday assistance rather than physical or medical tasks: conversation, shared meals, accompanied outings, light housekeeping, and help with errands. A companion caregiver does not assist with bathing, dressing, or any hands-on physical care, and typically doesn't require formal clinical certification.</p>
          <p>This level fits seniors who are largely independent but isolated, or who need help with tasks like transportation and light chores rather than physical assistance. Our <a href="companion-care">companion care services</a> are often the right starting point for a senior who is safe at home but could use consistent company and a hand with day-to-day logistics.</p>
          <p>Because companion caregivers aren't performing clinical or physical care tasks, the qualifications a family should look for are less about certification and more about reliability, personality fit, and experience working with older adults. That said, a reputable provider still screens and trains companion caregivers on things like fall awareness, recognizing signs of a medical concern, and knowing when to escalate to a supervisor.</p>

          <h2 id="personal-care">Personal Care: Hands-On Support With Daily Living</h2>
          <p>Personal care steps up to hands-on assistance with activities of daily living, the tasks a person truly cannot function without: bathing, dressing, grooming, toileting, transferring in and out of bed or a chair, and help with mobility. Personal care providers are typically trained caregivers, often certified as home health aides or care aides, though the work itself is non-clinical, they assist with physical tasks rather than performing medical procedures.</p>
          <p>This level is appropriate once a senior can no longer safely manage bathing or dressing alone, has become an increased fall risk during transfers, or needs consistent physical assistance throughout the day. Our <a href="personal-care">personal care services</a> combine this hands-on support with the same companionship and everyday help found in companion care, since most families need both.</p>
          <p>It's a common misconception that personal care requires a nursing background. It doesn't. Personal care aides are trained in safe techniques for assisting with mobility and hygiene, but they don't administer medications, perform wound care, or make clinical judgments about a senior's health, that's where nursing care becomes necessary instead.</p>
