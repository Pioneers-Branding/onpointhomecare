          <h2 id="nursing-care">Nursing Care: Clinical Support at Home</h2>
          <p>Nursing care is the highest and most specialized level of home support, delivered or directly supervised by a Registered Nurse or Licensed Practical Nurse. This includes medication administration and management, wound care, injections, catheter care, chronic disease monitoring for conditions like diabetes or heart failure, and coordination with physicians. Unlike companion or personal care, nursing care involves regulated clinical judgment, a nurse is legally accountable for the assessments and interventions they perform.</p>
          <p>Our <a href="home-nursing">home nursing services</a> are appropriate for seniors managing chronic conditions, recovering from a hospital stay, requiring wound care, or needing any medical task that goes beyond what a non-clinical caregiver is trained or permitted to do. Nursing care can also be layered on top of personal or companion support, so a senior might have a nurse visit twice weekly for medication management while a personal care aide helps with daily bathing and dressing the rest of the week.</p>

          <h2 id="cost-breakdown">Cost Breakdown</h2>
          <p>Hourly rates rise with the level of training and clinical responsibility involved. In British Columbia, private home care rates in 2026 typically run in a range of roughly $32 to $55 per hour depending on the type of care and provider. Companion care sits at the lower end of that range, focused on social interaction and light tasks. Personal care runs somewhat higher because it requires trained caregivers performing hands-on physical assistance. Nursing care sits at the top of the range because it requires a regulated health professional providing clinical services.</p>
          <p>Families in BC managing a chronic disability may also be eligible for provincial programs like <a href="home-care-cost">Choices in Supports for Independent Living (CSIL)</a>, which provides funding based on an assessed number of home support hours. It's worth discussing eligibility with your health authority alongside comparing private options, since public and private support can sometimes be combined depending on the situation.</p>
          <p>It's also worth thinking about cost in terms of total weekly spend rather than hourly rate alone. A senior who needs eight hours of companion care a week will often spend less overall than one who needs two hours of nursing visits, even though the nursing rate per hour is higher, simply because the actual clinical time required tends to be shorter. Comparing quotes based on the full weekly or monthly plan, not just the headline hourly rate, gives a much clearer picture of what a realistic care arrangement will cost.</p>

          <h2 id="how-to-choose">How to Choose the Right Level</h2>
          <p>Start by listing what your parent actually struggles with, not what feels like the "safe" or comprehensive choice. If the issue is loneliness, errands, or light chores, companion care is likely sufficient and the most cost-effective option. If your parent needs physical help with bathing, dressing, or getting around safely, personal care is the right fit. If there's a medical component, medication management, a wound, a chronic condition that needs monitoring, nursing care needs to be part of the plan, even if it's just a few visits a week alongside a lower level of daily support.</p>
          <p>Many seniors ultimately need a blend: companion-level social support most days, with personal care assistance for bathing, and periodic nursing visits for medication oversight. A knowledgeable provider should be able to build that mix rather than pushing every client toward a single fixed package.</p>
          <p>Be cautious of any provider who tries to sell every family the same package regardless of need. A senior who only needs occasional errands and company shouldn't be paying for a home health aide's hourly rate, and a senior managing a complex wound shouldn't be relying on a companion caregiver to notice signs of infection. Ask any provider you're considering to explain, specifically, why they're recommending a particular level of care for your parent's situation rather than a general tier.</p>

          <h2 id="care-can-change">Why Your Choice Doesn't Have to Be Permanent</h2>
          <p>One of the most common mistakes families make is treating this decision as permanent. Care needs change, often gradually and sometimes suddenly, after a fall, a hospital stay, or a diagnosis. What starts as companion care two mornings a week can reasonably grow into personal care, and later add nursing support, without starting over with a new provider each time. A good home care partner reassesses regularly and adjusts the plan rather than leaving a family to renegotiate everything from scratch.</p>
          <div class="quote-card-teal">
            <strong>From our clinical experience:</strong> The families who do best are the ones who treat the first care plan as a starting point, not a final decision. Revisiting it every few months, especially after any change in health, keeps the level of support matched to what's actually needed.
          </div>
          <p>A useful habit is scheduling a brief review with your care provider after any significant change: a hospitalization, a new diagnosis, a fall, or even a noticeable change in mood. These are the moments when a senior's needs most often shift from one level of care to the next, and catching the shift early usually means a smoother transition and fewer surprises down the road.</p>

