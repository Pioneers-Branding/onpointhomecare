          <h2 id="healthcare">Local Hospitals and Healthcare Access</h2>
          <p><strong>Richmond Hospital</strong>, operated by Vancouver Coastal Health at 7000 Westminster Highway, is the city's main acute care facility and the hospital most Richmond families interact with for emergency visits, surgeries, and discharge planning. Families coordinating a parent's transition home after a hospital stay often need care in place quickly, sometimes within a day or two of discharge, to manage medication schedules, wound care, or mobility support while healing.</p>
          <p>Because Richmond is geographically compact, home care visits tied to a Richmond Hospital discharge can typically be scheduled promptly once an assessment is complete. If your family is navigating a discharge right now, our <a href="hospital-to-home-care">hospital-to-home care</a> and <a href="post-discharge-nursing">post-discharge nursing</a> services are built specifically for that transition window.</p>

          <h2 id="services">Home Care Services Available in Richmond</h2>
          <p>Home care is not one fixed package. It typically ranges from a few hours of weekly support to around-the-clock nursing supervision, and the right level depends on your loved one's health, safety risks, and how much family caregiving is already happening. Services families in Richmond most often ask about include:</p>
          <ul>
            <li><a href="personal-care">Personal care</a>: bathing, dressing, grooming, and toileting support delivered with dignity and patience.</li>
            <li><a href="companion-care">Companion care</a>: conversation, light housekeeping, meal preparation, and transportation to appointments or family gatherings.</li>
            <li><a href="dementia-care">Dementia care</a>: structured routines and safety supervision for clients living with Alzheimer's or another form of cognitive decline.</li>
            <li><a href="home-nursing">Home nursing</a>: RN or LPN-delivered care such as medication management, catheter care, or <a href="wound-care">wound care</a> for more complex medical needs.</li>
            <li><a href="24-hour-home-care">24-hour home care</a> or <a href="overnight-care">overnight care</a>: continuous support for clients who are unsafe alone, particularly at night.</li>
            <li><a href="respite-care">Respite care</a>: short-term relief for a family member who has been the primary caregiver and needs a break.</li>
          </ul>
          <p>Every plan should start with a clinical assessment rather than a generic package, since a client recovering from a fall has very different needs from one managing early-stage dementia. Our <a href="services">full range of home care services</a> is designed to flex as those needs change over time.</p>

