        <div class="article-body">
          <p>One of the hardest parts of caring for someone with dementia is not knowing what comes next. Families often ask us the same question in different words: "Is this normal for where she's at, or is this a big jump?" Understanding the <strong>stages of dementia</strong> won't make the disease easier, but it gives you a framework for what to expect, so you're planning ahead of each transition instead of scrambling to react to it.</p>
          <p>The scale most clinicians reference is the Global Deterioration Scale (GDS), developed by Dr. Barry Reisberg, which breaks dementia progression into seven stages. Below, we walk through each one in plain language, along with what it tends to mean for daily care.</p>

          <h2 id="gds-scale">What the 7-Stage Scale Actually Measures</h2>
          <p>The GDS tracks how cognitive and functional ability changes over the course of dementia, from no detectable symptoms through to complete dependence on caregivers. It's important to understand this scale as a guide, not a strict timeline. Dementia doesn't progress identically in every person. Someone may skip visible symptoms of one stage, plateau at another stage for years, or progress through two stages in a matter of months. Use these stages to understand general direction and plan resources, not to predict an exact timeline for your own family.</p>

          <h2 id="progression-varies">How Progression Differs by Type of Dementia</h2>
          <p>The GDS was originally developed with Alzheimer's disease in mind, which is the most common form of dementia and tends to follow this seven-stage pattern fairly closely, typically with a gradual, steady decline over several years. Other types of dementia can progress differently, and it's worth understanding your loved one's specific diagnosis rather than assuming every dementia follows an identical path.</p>
          <p><strong>Vascular dementia</strong>, caused by reduced blood flow to the brain, often from small strokes, tends to progress in a step-wise pattern rather than a smooth decline. A person may remain stable for a period, then experience a noticeable drop after a new vascular event, rather than gradually worsening month by month.</p>
          <p><strong>Lewy body dementia</strong> often involves more day-to-day and even hour-to-hour fluctuation in alertness and cognitive ability than Alzheimer's, alongside visual hallucinations and movement symptoms similar to Parkinson's disease. Families sometimes describe this as their loved one seeming "almost like themselves" one day and significantly more confused the next.</p>
          <p><strong>Frontotemporal dementia</strong> frequently appears at a younger age and often begins with changes in personality, judgment, or language rather than memory loss, which can make the earliest stages harder to recognize using a memory-focused framework like the GDS.</p>
          <p>Because of these differences, the stage descriptions below are best used as a general roadmap for what tends to happen as dementia progresses, while your loved one's care team can help you understand how their specific diagnosis might follow a different rhythm.</p>

          <h2 id="stage-1-2">Stages 1 and 2: No Symptoms and Very Mild Changes</h2>
          <p><strong>Stage 1</strong> describes a person with no cognitive impairment at all: no memory problems, no symptoms detectable by a doctor or the person themselves. Everyone technically starts here.</p>
          <p><strong>Stage 2</strong> involves very mild cognitive decline, often indistinguishable from normal age-related forgetting. A person might notice they're misplacing familiar objects or blanking on words more than they used to, but these changes usually aren't apparent to family, friends, or even a doctor during a routine visit. Most people in stage 2 are not diagnosed with dementia, because at this point the changes are too subtle to separate from ordinary aging.</p>

          <h2 id="stage-3">Stage 3: Mild Cognitive Decline</h2>
          <p>This is often the stage where family members first start to notice something is different, even before a formal diagnosis. A person in stage 3 may have trouble finding the right word, forget names shortly after being introduced, misplace important items, or struggle to plan or organize. Performance at work or in complex social settings may decline noticeably, though the person can typically still live independently. Many people at this stage would be classified as having mild cognitive impairment (MCI) rather than dementia outright, since a formal dementia diagnosis usually isn't made until stage 4.</p>

