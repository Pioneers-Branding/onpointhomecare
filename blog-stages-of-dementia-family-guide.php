          <h2 id="stage-4">Stage 4: Mild Dementia</h2>
          <p>Stage 4 is typically when a clinical diagnosis of dementia is made. Symptoms become clear enough that they're difficult to miss: significant trouble managing finances, forgetting recent events, difficulty with complex tasks like planning a family event, and some withdrawal from social situations as the person becomes aware of their own struggles. Most people at this stage can still live at home and manage basic daily activities independently, but they typically need help with tasks that involve planning, organization, or multiple steps, such as managing medications or bills.</p>
          <p>This stage often lasts for a couple of years and is a reasonable window for putting practical supports in place gradually rather than all at once: a pill organizer with reminders, automatic bill payments, a shared calendar with family members, and an initial conversation with a lawyer about power of attorney and representation agreements while your loved one can still participate meaningfully in that planning.</p>

          <h2 id="stage-5">Stage 5: Moderate Dementia</h2>
          <p>This is often the stage where family caregivers start feeling real day-to-day strain. A person in stage 5 usually can no longer manage independently. They may need help choosing appropriate clothing for the weather or occasion, struggle to recall their address or phone number, and have gaps in memory about recent events or even significant details of their own history. Basic tasks like bathing and dressing typically still happen without full assistance, but reminders and supervision become necessary for safety.</p>
          <p>Driving is typically no longer safe by this stage, which is often a difficult transition for both the person and the family. Home safety also becomes a bigger focus here: removing trip hazards, securing stoves and medications, and considering door alarms if wandering has become a concern, since judgment about safety risks is often the first thing to decline noticeably at this point.</p>

          <h2 id="stage-6">Stage 6: Moderately Severe Dementia</h2>
          <p>Stage 6 involves a significant loss of independence. The person typically needs help with most activities of daily living, including dressing, bathing, and toileting. Personality and behavioral changes often become more pronounced here, including agitation, suspicion, compulsive behaviors, or wandering. Many people at this stage no longer recognize familiar faces reliably, including close family members, though they may still respond to a familiar voice or touch. Sleep disturbances and sundowning, increased confusion and agitation in the late afternoon and evening, are common in this stage.</p>
          <p>This is often the stage where families reassess whether care can safely continue at home without additional help, since the combination of physical care needs, incontinence, and behavioral symptoms typically exceeds what one family caregiver can manage alone on top of their own job, health, and family responsibilities. Bringing in professional support, even a few shifts a week, often becomes the difference between a sustainable arrangement and caregiver burnout.</p>

