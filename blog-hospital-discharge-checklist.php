          <h2 id="first-72">Why the First 72 Hours at Home Matter Most</h2>
          <p>A hospital discharge means a physician has determined someone is medically stable enough to leave. It doesn't mean the home is set up to receive them safely. That gap is where the majority of post-discharge complications happen: a missed medication dose, a fall while trying to manage alone, or a wound that isn't checked in time. The first 72 hours at home are consistently the highest-risk window, which is exactly why they're worth planning for in advance rather than improvising on the day.</p>

          <h2 id="questions">Before Discharge: Questions to Ask the Care Team</h2>
          <p>Whenever possible, have these answered before your parent leaves the ward:</p>
          <ul>
            <li>What is the complete, updated list of medications, including anything stopped or changed during the stay?</li>
            <li>What specific activity restrictions apply (weight-bearing limits, lifting restrictions, driving)?</li>
            <li>What wound, dressing, or drain care is needed, and who is doing it at home?</li>
            <li>What symptoms should prompt a call to the family doctor versus a return to the ER?</li>
            <li>Has a referral for home nursing or home care already been submitted, or does the family need to arrange it?</li>
          </ul>

          <h2 id="medications">Medications: Avoiding the #1 Cause of Readmission</h2>
          <p>Medication changes are one of the most common, and most preventable, causes of a return trip to hospital. It's common for two or three medications to be stopped, started, or have their dose changed during a hospital stay, and without a clear reconciliation, families often end up combining an old pillbox with a new prescription, sometimes duplicating or missing a drug entirely.</p>
          <div class="article-callout">
            <div class="article-callout-title">
              <svg class="icon-sm" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2"><circle cx="12" cy="12" r="10"></circle><line x1="12" y1="16" x2="12" y2="12"></line><line x1="12" y1="8" x2="12.01" y2="8"></line></svg>
              Clinical Tip
            </div>
            <p>Before leaving the hospital, ask for a single, current medication list and physically compare it line-by-line against the pill bottles already at home. Discard or clearly set aside anything no longer prescribed so it can't be taken by mistake.</p>
          </div>

          <h2 id="equipment">Equipment and Home Setup</h2>
          <p>Depending on the reason for admission, your parent may need equipment waiting at home before they arrive, such as a hospital bed, a commode, a walker, or a shower chair. Delivery of medical equipment can take a day or more to arrange, so it's worth asking about equipment needs as soon as discharge is mentioned, not after it's confirmed.</p>

          <h2 id="followup">Arranging Follow-Up Appointments</h2>
          <p>A discharge summary usually recommends follow-up with a family doctor, surgeon, or specialist within one to two weeks. Book this before leaving the hospital if possible. Family doctor calendars fill quickly, and a missed follow-up window is a common reason small problems go unnoticed until they become bigger ones.</p>

          <h2 id="who-is-there">Who Will Be There When They Arrive Home?</h2>
          <p>Someone medically fragile should not be the one unlocking an empty house. Plan who will be present for at least the first 24 to 48 hours, and be honest about whether that person can manage medication schedules, mobility assistance, and meal preparation on top of their own responsibilities. This is often the point where families reach out about <a href="post-discharge-nursing">post-discharge nursing</a> or short-term care aide support. Even a temporary arrangement for the first week or two can prevent the crisis of trying to do it all alone.</p>

          <h2 id="warning-signs">Warning Signs That Mean Call the Doctor</h2>
          <p>General warning signs worth acting on quickly include a fever, new or worsening confusion, shortness of breath, a wound that becomes red, warm, or draining, chest pain, or an inability to keep food or medication down. When in doubt, call: it's always better to check with a nurse or physician than to wait and see.</p>
          <p>OnPoint's <a href="hospital-to-home-care">hospital-to-home transition service</a> exists specifically to close this gap: our nurses can meet your parent at the hospital, translate the discharge instructions into a daily home schedule, and arrange the right level of nursing or personal care from day one.</p>

