        <div class="article-body">
          <p>Most home care conversations start with fairly ordinary needs: help with bathing, a hand with meals, someone to check in during the day. But for a meaningful number of families in Metro Vancouver, the situation is more serious than that, a chronic illness that's progressed, equipment that requires regular monitoring, or a wound that needs a trained clinical eye. <strong>Complex care at home</strong> exists for exactly this gap: seniors whose medical needs go beyond what a non-clinical caregiver is trained or legally permitted to manage, but who don't necessarily need to live in a facility to get that level of support.</p>
          <p>This guide explains what complex care actually covers, who typically needs it, and how a nurse-led care team is structured, so you can recognize whether your family's situation calls for this level of support.</p>

          <h2 id="what-is-complex-care">What Complex Care at Home Actually Means</h2>
          <p>Complex care is person-centered, nurse-supervised support for seniors managing a chronic illness or advanced medical condition that requires more than standard personal care. Unlike basic home care, which is often short-term or focused on daily living tasks, complex care is typically ongoing and built around a formal care plan developed and regularly reviewed by a Registered Nurse, in coordination with the senior's physician and any specialists involved.</p>
          <p>The defining feature isn't the number of hours of care, it's the level of clinical judgment required. A senior on complex care may need help with the same daily tasks as anyone else, dressing, meals, mobility, but layered with clinical monitoring, specialized equipment management, or interventions that only a trained nurse or closely supervised caregiver can safely perform.</p>

          <h2 id="who-needs-it">Who Typically Needs Complex Care</h2>
          <p>Complex care is generally appropriate for seniors managing conditions such as advanced Parkinson's disease, ALS, multiple sclerosis, significant stroke recovery, severe COPD or other advanced respiratory conditions, and stage 3 or 4 pressure wounds. It also applies to seniors who are tracheostomy or ventilator dependent, require ongoing catheter or stoma care, or are recovering from major surgery with a complicated recovery course. What these situations share is that daily management carries real medical risk if it's handled incorrectly, missed signs of infection, improper wound care, or a mismanaged feeding tube can lead to a hospital readmission.</p>
          <p>Age alone is never the deciding factor. A senior can be otherwise active and cognitively sharp and still require complex care because of a single serious condition, such as a stage 4 pressure wound following a long hospital stay. Conversely, an older adult with several mild chronic conditions that are well controlled may not need complex care at all, standard personal care and periodic nursing check-ins may be entirely sufficient. The determining question is always whether the day-to-day management of the condition requires ongoing clinical judgment.</p>
