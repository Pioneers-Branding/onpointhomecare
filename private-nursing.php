        <div class="svc-block">
          <span class="svc-block-num">Component 01</span>
          <h3>A Schedule Built Around the Person</h3>
          <p>Publicly funded visits necessarily run to the service's timetable. Private nursing runs to yours.</p>
          <p>That sounds like a small thing until you consider what it actually governs: whether someone gets help washing before breakfast or after lunch, whether medication is given at the time it was prescribed for, whether the person is helped to bed at their own bedtime rather than at half past six because that is when the round reached them.</p>
          <p>For an older adult, a day that follows their own rhythm rather than somebody else's is a substantial part of what dignity actually consists of.</p>
          <ul class="svc-block-list">
            <li>Visit times chosen by the family</li>
            <li>Visit length matched to the work required</li>
            <li>Morning, evening, overnight and weekend availability</li>
            <li>Regular scheduled visits or ad-hoc arrangements</li>
            <li>Short-notice cover where staffing allows</li>
            <li>Schedule reviewed as routines change</li>
          </ul>
        </div>
        <div class="svc-block">
          <span class="svc-block-num">Component 02</span>
          <h3>Continuity of Nursing Staff</h3>
          <p>We roster for continuity deliberately, because it is one of the few things that reliably improves the experience of care for an older adult &mdash; particularly where there is memory impairment, anxiety, or a natural reluctance to be helped with personal tasks by a stranger.</p>
          <p>A familiar nurse also provides better clinical care. Someone who has seen this person weekly for three months notices the change that a first-time attender cannot.</p>
          <ul class="svc-block-list">
            <li>Rostering planned for familiar faces</li>
            <li>Small consistent care teams rather than a rotating pool</li>
            <li>Detailed handover where a regular nurse is unavailable</li>
            <li>Introduction of new staff before they attend alone where possible</li>
            <li>Client and family feedback on staffing fit</li>
            <li>Documented care plans so continuity survives absence</li>
          </ul>
        </div>
        <div class="svc-block">
          <span class="svc-block-num">Component 03</span>
          <h3>Scope Set by Need, Not by Category</h3>
          <p>Funded services necessarily work within eligibility categories. Privately arranged care can be built around what is actually needed, including the things that fall between categories.</p>
          <p>In practice this means a visit can cover a dressing change and medication and a proper conversation, rather than one of the three because that is what the allocation permits.</p>
          <ul class="svc-block-list">
            <li>Health monitoring and chronic condition oversight</li>
            <li>Medication administration and regimen supervision</li>
            <li>Wound care and dressing management</li>
            <li>Post-hospital and post-surgical support</li>
            <li>Continence, catheter and stoma care</li>
            <li>Personal care delivered by nursing staff where preferred</li>
          </ul>
        </div>
        <div class="svc-block">
          <span class="svc-block-num">Component 04</span>
          <h3>Working Alongside Publicly Funded Care</h3>
          <p>Private nursing is not an alternative to public home health for most families &mdash; it is a supplement to it. The funded team continues doing what it is allocated to do, and private visits fill the specific gaps.</p>
          <p>We coordinate around the existing plan deliberately, so that nobody is duplicating work, contradicting instructions, or leaving a task undone because each service assumed the other had it.</p>
          <ul class="svc-block-list">
            <li>Coordination with the funded home health team</li>
            <li>One shared care plan rather than parallel ones</li>
            <li>Clear division of which service does what</li>
            <li>Communication with the family physician</li>
            <li>Top-up visits where the allocation is insufficient</li>
            <li>Cover during gaps in the funded schedule</li>
          </ul>
        </div>
        <div class="svc-block">
          <span class="svc-block-num">Component 05</span>
          <h3>Scaling Up and Down as Circumstances Change</h3>
          <p>Care needs are not stable. A chest infection, a fall, a family carer's holiday or a bereavement can change what is required within a week &mdash; and equally, a good recovery can reduce it.</p>
          <p>Because the arrangement is direct, it can move in both directions without a reassessment process. More visits during a difficult stretch; fewer when things settle. We will actively tell you when we think you need less.</p>
          <ul class="svc-block-list">
            <li>Increase cover during illness or crisis</li>
            <li>Reduce visits as recovery progresses</li>
            <li>Temporary respite cover for family carers</li>
            <li>Overnight or continuous care where needs escalate</li>
            <li>Regular review of whether the level is still right</li>
            <li>Honest advice when less care is appropriate</li>
          </ul>
        </div>
        <div class="svc-block">
          <span class="svc-block-num">Component 06</span>
          <h3>Transparent Costs and Written Agreements</h3>
          <p>Cost is the question families ask first and are most often given a vague answer to. We give written costs before any care begins, covering the visit rate, the schedule and what is included.</p>
          <p>We do not begin work on an unclear arrangement, and we do not change the basis of it without telling you first. If the level of care changes, so does the written agreement.</p>
          <ul class="svc-block-list">
            <li>Written costs provided before care starts</li>
            <li>Clear statement of what each visit includes</li>
            <li>No commitment to a minimum number of hours</li>
            <li>Advance notice of any change to the arrangement</li>
            <li>Itemised, understandable invoicing</li>
            <li>Honest advice on whether the spend is warranted</li>
          </ul>
        </div>
