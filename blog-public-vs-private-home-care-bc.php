          <h2 id="cost-comparison">Cost Comparison: Public vs. Private</h2>
          <p>Public home support fees are income-tested rather than market-priced. Depending on household income, a family may pay a modest daily rate, a flat monthly amount capped around $300, or nothing at all if income falls below the threshold set out in provincial fee regulations.</p>
          <p>Private home care in the Metro Vancouver area is typically billed hourly, with rates that vary by the type of care provided. As a general guide, companionship and light homemaking support tend to sit at the lower end of the range, personal care support (bathing, dressing, mobility) in the middle, and specialized or nursing-level care at the higher end. Because rates vary by agency, caregiver qualifications, and hours booked, we recommend treating any number you see online as a starting point and requesting a written quote for your specific situation. Our <a href="home-care-cost">home care cost guide</a> breaks down typical pricing ranges and what tends to drive costs up or down.</p>

          <h2 id="whats-covered">What Each System Actually Covers</h2>
          <p>Public home support is focused narrowly on personal care and safety tasks tied to activities of daily living. It generally does not cover housekeeping beyond what relates directly to hygiene, meal preparation beyond basic safety needs, transportation, companionship visits, or extended overnight supervision.</p>
          <p>Private home care can be shaped around whatever a family actually needs, which is often a wider circle than personal care alone: transportation to appointments, help with a shower and a hot meal on the same visit, companionship for someone who is isolated, or a caregiver who stays through the night after a fall. This flexibility is usually the main reason families add private care even when public home support is already in place.</p>

          <h2 id="wait-times">Wait Times and Availability</h2>
          <p>Because public home support is delivered through a public system with finite staffing, the time between a referral and the first visit can vary considerably depending on the health authority, current caseloads, and how urgent the assessed need is. Hospital discharge cases are often prioritized, but a routine community referral can take longer to move through assessment and scheduling.</p>
          <p>Private home care generally moves faster because it operates outside that queue. Most agencies can complete an assessment and have a caregiver in the home within a matter of days, which matters most in the days immediately following a hospital stay, a fall, or a sudden decline that will not wait for a public assessment slot.</p>

          <h2 id="hybrid-model">Why Many Families Use Both</h2>
          <p>In practice, the families we work with rarely pick one system and stick with it exclusively. A common pattern looks like this: the health authority's home support worker handles a short morning visit for bathing and medication reminders, while a private caregiver from OnPoint covers afternoons, evenings, weekends, or overnight hours, along with the companionship and household tasks that public home support does not include.</p>

          <div class="quote-card-teal">
            <strong>From our clinical experience:</strong> The families who plan best treat public home support as one piece of a larger care plan, not the whole plan. Applying for it costs nothing, and layering private care around it usually creates a schedule that actually matches how the person lives, not just what one program is funded to deliver.
          </div>

          <h2 id="sample-week">A Realistic Week: What a Hybrid Plan Looks Like</h2>
          <p>It can be hard to picture how public and private care actually fit together until you see it laid out. A typical week for one of our hybrid clients might look like this: a health authority home support worker visits Monday, Wednesday, and Friday mornings for a 45-minute personal care visit, helping with bathing, dressing, and medication reminders. On the other days, and every evening, a private caregiver from OnPoint arrives for two to three hours to prepare a hot meal, provide companionship, handle light housekeeping, and assist with an evening routine. On weekends, when public home support is often unavailable or reduced, private care covers the full gap.</p>
          <p>No two households need the same mix. Some families use private care only for a few hours a week to supplement daily public visits; others use it for full daytime coverage while a public worker handles a single morning task. The point of a hybrid plan isn't a fixed formula, it's building a weekly rhythm around what your specific parent actually needs, rather than accepting whatever a single program happens to offer.</p>

          <h2 id="misconceptions">Common Misconceptions Worth Clearing Up</h2>
          <p>A few assumptions trip families up more than any other part of this decision. The first is thinking that applying for public home support disqualifies you from also paying for private care, which isn't the case; the two systems don't interact with each other in that way. The second is assuming private home care must mean full-time, expensive coverage, when in practice most private agencies will schedule as little as a few hours a week. The third is believing that a single home support assessment is permanent; needs, and therefore funded hours, can be reassessed over time as a parent's condition changes.</p>

          <h2 id="choosing">How to Decide Where to Start</h2>
          <p>If your family has time before a crisis forces a decision, it is worth doing both things at once: start the public home support assessment through your health authority, and book a private <a href="care-assessment">care assessment</a> to understand what a custom plan would look like and cost. Comparing the two side by side, rather than guessing from general information online, is the fastest way to build a plan that actually fits your parent's routine, your family's schedule, and your budget.</p>
          <p>Whichever direction your family leans, the underlying goal is the same: enough consistent, safe support that your loved one can remain in the home they know, for as long as that remains the right choice.</p>

