        <div class="article-body">
          <p>One of the first questions families ask us at OnPoint is some version of the same thing: "Can't the government just send someone?" It is a fair question, and the honest answer is: sometimes, partially, and not always on the schedule your family needs. Understanding <strong>home support vs private home care BC</strong> options early, before a crisis forces a fast decision, gives Metro Vancouver families far more control over how a parent is cared for at home.</p>
          <p>Both systems exist for good reason, and neither is inherently "better." They are built to solve different problems. This guide walks through how each one actually works, what each one costs, and why most families we support end up combining the two rather than choosing just one.</p>

          <h2 id="the-basic-difference">The Basic Difference Between the Two Systems</h2>
          <p>Public home support is a subsidized government service, delivered through your regional health authority (Vancouver Coastal Health, Fraser Health, or Providence Health Care, depending on where you live in Metro Vancouver), after a clinical assessment confirms you need it. Private home care is a paid service you arrange directly with an agency, on your own timeline, without needing to qualify through a government assessment first.</p>
          <p>In short: public home support is need-assessed and partially income-tested, while private home care is available to anyone willing to pay for it, whenever they need it.</p>

          <h2 id="public-home-support">How Public Home Support Works in BC</h2>
          <p>To access publicly funded home support, a resident (or a family member on their behalf) contacts the health authority, often by calling 8-1-1, or asks a family doctor, discharge planner, or hospital social worker to make a referral. A case manager, typically a nurse or health professional, then completes an in-home assessment to determine what level of personal care is medically needed.</p>
          <p>If approved, a home support worker is scheduled to visit for specific, time-limited tasks: bathing, dressing, transferring, mobility assistance, and medication reminders. Visits are typically short, often in the range of 30 to 90 minutes, and are scheduled around the health authority's staffing capacity rather than a family's preferred routine. Home support workers are employed or contracted by the health authority, not chosen by the family.</p>
          <p>Eligibility generally requires BC residency, a completed clinical assessment, and an up-to-date income tax filing, since fees for ongoing service are calculated based on income under BC's Continuing Care Fees framework. Many lower-income clients pay a small daily fee or nothing at all, while the province caps charges at $300 per month for clients with earned income above a certain level. It is worth confirming your household's exact rate with your health authority, since it changes based on individual financial circumstances.</p>
          <p>It also helps to know who delivers this care. Home support workers in the public system are employed or contracted by the health authority and rotate across a caseload of clients, which means your parent may see a different worker on different days, particularly during illness, vacation, or staff turnover. The health authority manages scheduling centrally, so families generally cannot request a specific worker or a guaranteed consistent face, even though most health authorities do try to maintain continuity where staffing allows.</p>

          <h2 id="private-home-care">How Private Home Care Works</h2>
          <p>Private home care is arranged directly with a licensed home care agency like OnPoint. There is no referral requirement, no waitlist tied to health authority capacity, and no income test. A family can typically begin service within days of an initial <a href="care-assessment">care assessment</a>, choosing the hours, frequency, and type of support that fits their situation.</p>
          <p>Private agencies generally offer a broader menu of services than public home support, including companionship, light housekeeping, meal preparation, transportation, overnight and <a href="services">24-hour care</a>, and skilled nursing tasks such as wound care or medication management, depending on the agency's staffing model. Families also have more say in caregiver matching, schedule consistency, and how quickly the plan can change as needs evolve.</p>
          <p>Because private home care operates outside the public system, families also have more room to adjust the plan as circumstances shift. If a parent's needs increase after a fall or a hospital stay, a private agency can typically add hours or change the scope of care within days, rather than waiting for a new assessment to work its way through the health authority's process. That responsiveness is one of the main reasons private care tends to fill the gaps that public programs, by design, cannot.</p>

