          <span class="svc-block-num">Component 01</span>
          <h3>How Continuous Cover Is Staffed</h3>
          <p>Round-the-clock support is provided by a rostered team working in shifts. No one person can stay alert and competent across twenty-four hours, and any provider suggesting otherwise is describing something that will fail.</p>
          <p>We build the roster from the smallest practical team, because continuity matters enormously to a client who is confused or anxious &mdash; a rotating cast of strangers can undo most of the benefit. Rosters are shared in advance so the family knows who is coming and when.</p>
          <p>Every shift change involves a structured handover: what happened, what was eaten, how the night went, what changed, and what the next shift needs to watch.</p>
          <ul class="svc-block-list">
            <li>A rostered team, not one stretched individual</li>
            <li>Planned day and night shift rotation</li>
            <li>The smallest practical team for familiarity</li>
            <li>Rosters shared with the family in advance</li>
            <li>Structured written and verbal handover each shift</li>
            <li>Contingency cover planned for illness and leave</li>
          </ul>
        </div>
        <div class="svc-block">
          <span class="svc-block-num">Component 02</span>
          <h3>Daytime Support and Structure</h3>
          <p>Continuous care is not somebody sitting watching. The day has a shape: getting up, washing and dressing, breakfast, activity, lunch, rest, company, an outing if it is possible, an evening routine.</p>
          <p>Keeping that structure intact does real work, particularly where there is cognitive impairment. Routine is orientation, and a day that has collapsed into television and dozing accelerates decline faster than most families realise.</p>
          <ul class="svc-block-list">
            <li>Personal care and daily living support</li>
            <li>Meal preparation and eating support</li>
            <li>Mobility support and safe transfers</li>
            <li>Company, conversation and activities</li>
            <li>Encouragement to stay active and go outdoors</li>
            <li>Household tasks and keeping the home usable</li>
          </ul>
        </div>
        <div class="svc-block">
          <span class="svc-block-num">Component 03</span>
          <h3>Overnight Presence and Night-Time Risk</h3>
          <p>Nights are where most of the risk sits and where families are least able to cover. Confusion often worsens after dark, the trip to the bathroom in the dark is where falls happen, and something that starts at two in the morning can go unnoticed until breakfast.</p>
          <p>Depending on what the nights actually involve, cover is either waking &mdash; an aide awake and present throughout &mdash; or sleeping, where the aide is in the house and available but not up all night. We will assess honestly which one the situation requires rather than selling you the cheaper option.</p>
          <ul class="svc-block-list">
            <li>Waking or sleeping night cover as assessed</li>
            <li>Support to the bathroom during the night</li>
            <li>Response to confusion and sundowning</li>
            <li>Repositioning for comfort where needed</li>
            <li>Immediate response to falls or distress</li>
            <li>A settled, familiar presence through the night</li>
          </ul>
        </div>
