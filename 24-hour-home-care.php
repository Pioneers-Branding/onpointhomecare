          <h3>Working With Nursing and Other Services</h3>
          <p>Twenty-four hour home care is non-clinical. Where a client also has clinical needs &mdash; wound care, medication administration, health monitoring &mdash; those are provided by nursing staff alongside the continuous cover.</p>
          <p>Our Lead Registered Nurse oversees the care plan in either case, which means the aides providing daily support have somewhere to escalate to when they notice something, rather than a concern sitting in a notebook.</p>
