          <span class="svc-block-num">Component 04</span>
          <h3>Supervision and Household Safety</h3>
          <p>A large part of what continuous cover provides is simply that somebody is there when something happens &mdash; the cooker left on, the front door opened at midnight, the fall in the hallway, the moment of acute confusion.</p>
          <p>It also means the ordinary household risks that build up when somebody is struggling alone stop building up. The fridge is not full of spoiled food. The post gets opened. The heating is on when it should be.</p>
          <ul class="svc-block-list">
            <li>Continuous supervision and presence</li>
            <li>Kitchen and household safety</li>
            <li>Door and wandering supervision</li>
            <li>Immediate response to falls and incidents</li>
            <li>Management of everyday household risks</li>
            <li>Documented record of incidents and changes</li>
          </ul>
        </div>
