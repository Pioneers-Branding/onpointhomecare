          <h2 id="who-needs-it">Who Typically Needs It</h2>
          <p>Not every discharge requires nursing follow-up. Post-discharge nursing tends to make the biggest difference for people who have had major or complex surgery, a new or worsening chronic condition such as congestive heart failure, COPD, or diabetes, a fall or fracture, or any hospitalization that left them with new equipment, a new medication regimen, or reduced mobility. It is also valuable for anyone living alone, or whose family caregiver feels unsure about managing a clinical task like a dressing change safely.</p>
          <p>Age matters too. Older adults are more likely to be sent home with several medication changes at once and are more vulnerable to the small warning signs, like a slight change in swelling or confusion, that can signal a bigger problem developing.</p>
          <p>It's also worth considering the caregiver's own confidence, not just the patient's medical complexity. A family member who feels uneasy about changing a dressing correctly or checking a blood pressure reading accurately is a reasonable signal to bring in professional support, even if the underlying recovery is otherwise expected to go smoothly.</p>

          <h2 id="vs-home-support">Post-Discharge Nursing vs. Home Support</h2>
          <p>Families often use "nurse" and "caregiver" interchangeably, but the two roles are legally and clinically distinct. A Registered Nurse can perform clinical tasks: changing a wound dressing, administering certain medications, assessing vital signs, and making judgment calls about when a symptom needs a physician's attention. A home support worker or caregiver, by contrast, focuses on non-clinical daily living tasks: bathing, dressing, meal preparation, light housekeeping, and companionship.</p>
          <p>Many recoveries actually need both, just at different intensities. A short course of nursing visits addresses the clinical risk in the first few weeks, while ongoing <a href="post-discharge-nursing">post-discharge nursing and home care support</a> can continue at a lighter touch once the acute risk has passed.</p>

          <h2 id="first-visit">What to Expect at the First Visit</h2>
          <p>A first post-discharge visit usually starts with a full review of the discharge paperwork, a head-to-toe assessment, and a walk-through of every medication in the home. The nurse will typically check the surgical site or area of concern, take baseline vital signs to compare against future visits, and ask detailed questions about diet, mobility, sleep, and pain control. Before leaving, a good nurse will leave the family with a clear, written list of "call us if you see this" warning signs specific to that patient's condition, not a generic pamphlet.</p>

          <h2 id="how-long">How Long Does It Last?</h2>
          <p>Post-discharge nursing is intentionally short-term. Depending on the complexity of the recovery, it might mean a single visit to confirm everything looks stable, or a series of visits over one to four weeks while a wound heals or a medication regimen is stabilized. It is not designed to replace ongoing home care, and a nurse experienced in transitional care will tell you early on when it's appropriate to step down to a lighter level of support, or step up if recovery isn't progressing as expected.</p>

          <h2 id="warning-signs">Signs You May Need More Support</h2>
          <p>Contact your family doctor or care team if you notice increasing redness, swelling, or drainage at a wound site, a fever, new or worsening confusion, shortness of breath, chest pain, or a fall. These can be signs of infection, medication side effects, or a complication that needs medical evaluation rather than home monitoring alone. When in doubt, it is always safer to call than to wait and see.</p>
          <p>If your family is finding it hard to keep up with dressing changes, medication timing, or simply keeping a close enough eye on things day to day, that is itself a sign it's time to bring in professional support rather than trying to manage everything alone.</p>

          <div class="quote-card-teal">
            <strong>From our clinical experience:</strong> The families who avoid a return trip to the hospital are rarely the ones with the fewest complications. They're the ones who had someone checking in early enough to catch a small problem before it became a big one.
          </div>

          <h2 id="getting-started">Getting Started in Metro Vancouver</h2>
          <p>If a hospital discharge is coming up, the best time to arrange nursing support is before the discharge date, not after a problem appears. Our nursing team can review the discharge summary with your family, build a short-term visit plan around the specific risks in that recovery, and coordinate directly with the discharging hospital or the family physician so nothing falls through the cracks in the handoff.</p>
          <p>Even if a discharge has already happened and your family is a few days in, it's not too late to bring in nursing support. A first visit can still catch a developing medication mismatch, reassess a wound, or simply confirm that recovery is on track, which often brings real peace of mind to a family that has been managing everything alone since leaving the hospital.</p>

