        <div class="article-body">
          <p>Leaving the hospital feels like the finish line, but for many patients and families, the first two weeks at home are actually the riskiest part of recovery. New medications, a healing wound, unfamiliar equipment, and a body that is still fragile all collide at once, often with no clinician in the room to catch a problem early. This is the gap that post-discharge nursing care is built to close.</p>
          <p>As a Registered Nurse who has managed hundreds of transitions from hospital to home across Metro Vancouver, I've seen how a few well-timed nursing visits in that first week can be the difference between a smooth recovery and a trip back to the emergency room. This guide explains what post-discharge nursing care actually involves, who benefits most, and how to know if your family needs it.</p>

          <h2 id="what-is-it">What Is Post-Discharge Nursing?</h2>
          <p>Post-discharge nursing care is short-term, clinical care delivered by a Registered Nurse in a patient's home in the days and weeks immediately after a hospital stay, surgery, or emergency department visit. Unlike general home support, it is a skilled nursing service: the nurse is trained to assess a wound, interpret vital signs, manage complex medications, and recognize when a symptom needs urgent medical attention rather than simply monitoring for comfort.</p>
          <p>The goal is specific and practical: help the patient safely bridge the period between "still recovering under a physician's care" and "back to their normal baseline," while giving family caregivers the confidence and knowledge to support them in between visits.</p>

          <h2 id="what-it-includes">What a Post-Discharge Nurse Actually Does</h2>
          <p>The exact scope depends on the reason for the hospital stay, but a typical post-discharge nursing plan can include:</p>
          <ul>
            <li><strong>Wound and surgical site checks</strong>, including dressing changes and monitoring for early signs of infection.</li>
            <li><strong>Medication reconciliation</strong>, comparing the discharge summary against what is actually in the home, since new prescriptions, dose changes, and discontinued medications are among the most common sources of post-hospital complications.</li>
            <li><strong>Vital sign monitoring</strong>, such as blood pressure, heart rate, oxygen levels, and temperature, tracked against what is normal for that individual patient.</li>
            <li><strong>Catheter, ostomy, or drain care</strong> for patients discharged with equipment they have not managed before.</li>
            <li><strong>Chronic disease follow-up</strong>, checking in on conditions like heart failure or diabetes that may have been destabilized by the hospitalization itself.</li>
            <li><strong>Family and caregiver education</strong> on exactly what to watch for and who to call if something changes between visits.</li>
          </ul>

          <div class="article-callout">
