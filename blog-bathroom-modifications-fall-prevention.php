        <div class="article-body">
          <p>Bathroom safety for seniors is not just one item on a longer home safety list. It deserves its own plan, because more falls happen in and around the bathroom than in any other room of the house. Wet tile, a high tub wall, and a rushed transfer onto or off the toilet create a combination of hazards that a living room or kitchen simply doesn't have.</p>
          <p>According to a CDC surveillance study of nonfatal bathroom injuries, an estimated 234,000 people were treated in U.S. emergency departments for bathroom injuries in a single year, and 81.1% of those injuries were caused by a fall. Older adults were also more likely than younger people to be hurt on or near the toilet rather than in the shower or tub itself, which points to transfers, not just wet floors, as a major risk. Below are the five bathroom modifications our nursing team recommends most often for families in Metro Vancouver, in the order we'd usually tackle them.</p>

          <h2 id="why-bathroom">Why the Bathroom Is the Highest-Risk Room</h2>
          <p>A few things make bathrooms uniquely risky for older adults. Surfaces are hard and often wet, which turns a minor stumble into a fall with real force behind it. Space is tight, so there's little room to catch a wobble before it becomes a fall. And bathroom visits are frequently rushed, whether due to urgency, nighttime grogginess, or simply wanting to get the transfer over with quickly. None of this means a fall is inevitable. It means the room rewards a small number of specific, well-placed changes more than almost any other space in the home.</p>

          <h2 id="grab-bars">1. Grab Bars Anchored Into Studs, Not Suction Cups</h2>
          <p>Grab bars are the single most recommended bathroom modification, and for good reason: they give a person something solid to hold during the exact moments they're most likely to lose balance, standing up from the toilet, stepping over a tub wall, or steadying themselves on a wet floor. The catch is that a grab bar is only as safe as its installation. Suction-cup bars marketed as "no drilling required" can release suddenly under a person's full weight, particularly on textured tile, which can turn a minor stumble into a serious fall.</p>
          <p>A properly installed bar is anchored into wall studs or blocking, positioned based on the individual's height and how they actually move through the space, not just placed wherever looks tidy. Most bathrooms benefit from at least one bar beside the toilet and one or two inside the shower or tub, angled for the way that specific person reaches and pulls.</p>

          <div class="article-callout">
            <div class="article-callout-title">
