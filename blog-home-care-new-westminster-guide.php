          <h2 id="costs">What Home Care Costs in New Westminster</h2>
          <p>As across Metro Vancouver, home care in New Westminster is typically priced by the hour, with total cost depending on weekly hours needed and whether the care requires a caregiver, a Licensed Practical Nurse, or a Registered Nurse. A few hours of weekly companion care costs meaningfully less than continuous nursing support, and many families start with a smaller number of hours and adjust from there. Our <a href="home-care-cost">home care cost guide</a> covers the main pricing factors, and a free in-home assessment gives an exact estimate for your family's situation.</p>

          <h2 id="getting-started">How to Get Started</h2>
          <p>Getting started in New Westminster follows the same three steps as anywhere in our service area: an initial conversation about what's changed at home, an in-home assessment where a nurse evaluates safety and medical needs, and a care plan matched to a caregiver familiar with your neighborhood, whether that's Queens Park, Sapperton, or the Quay.</p>
          <p>If you're ready to talk it through, reach out through our <a href="contact">contact page</a>, or request a free <a href="care-assessment">in-home care assessment</a> to build a plan specific to your family's needs in New Westminster.</p>

