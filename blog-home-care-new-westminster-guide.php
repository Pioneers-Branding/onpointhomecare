          <h2 id="healthcare">Royal Columbian Hospital and Discharge Planning</h2>
          <p><strong>Royal Columbian Hospital</strong>, in the Sapperton neighborhood, is a Level 1 trauma centre and one of the largest and busiest hospitals in the Fraser Health region, serving not just New Westminster but a much wider referral area. Because it handles high-acuity trauma and surgical cases, many New Westminster families first encounter home care while planning a discharge after a serious injury, surgery, or cardiac event.</p>
          <p>That transition window, the first days home after a hospital stay, is when the risk of a fall, medication mix-up, or unplanned return to the ER is highest. Our <a href="hospital-to-home-care">hospital-to-home care</a> and <a href="post-discharge-nursing">post-discharge nursing</a> services are built specifically to support that period, and New Westminster's central location means a caregiver or nurse can often be arranged quickly once discharge planning begins.</p>

          <h2 id="services">Home Care Services Available in New Westminster</h2>
          <p>Home care needs range from light companionship to full nursing supervision, and the right starting point depends on your loved one's specific health and safety situation. Services New Westminster families often ask about include:</p>
          <ul>
            <li><a href="personal-care">Personal care</a>: bathing, dressing, and hygiene support, with special attention to older bathroom layouts.</li>
            <li><a href="companion-care">Companion care</a>: company, light housekeeping, meal prep, and transportation around the city.</li>
            <li><a href="care-after-a-fall">Care after a fall</a>: recovery support and safety planning, particularly relevant in multi-level heritage homes.</li>
            <li><a href="wound-care">Wound care</a> and <a href="post-operative-care">post-operative care</a>: nursing-level support following surgery at Royal Columbian.</li>
            <li><a href="dementia-care">Dementia care</a>: structured routines and supervision for clients with memory loss.</li>
            <li><a href="overnight-care">Overnight care</a>: nighttime support for clients who are unsafe alone after dark.</li>
          </ul>
          <p>Every plan should be based on an in-home clinical assessment rather than a fixed package, since the needs in a Queens Park character home differ from those in a Quay high-rise. Our full <a href="services">home care services</a> page outlines everything available if you'd like to explore options first.</p>

          <div class="quote-card-teal">
            <strong>From our clinical experience:</strong> In older New Westminster homes, some of the most valuable early conversations aren't about medical needs at all, they're about the stairs, the bathroom layout, and the doorways a wheelchair or walker actually has to fit through.
