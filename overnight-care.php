            <span class="faq-q-text">What is the difference between waking and sleeping night cover?</span>
            <span class="faq-q-icon">+</span>
          </button>
          <div class="faq-content">
            <p>A waking night means the carer stays awake and present throughout, actively available the whole time. A sleeping night means they are in the house asleep and can be woken if needed. Waking cover costs more and is necessary where the night genuinely involves work &mdash; frequent waking, repositioning, continence care or agitation. We will assess which one your situation requires and tell you honestly, including when the cheaper option is sufficient.</p>
          </div>
