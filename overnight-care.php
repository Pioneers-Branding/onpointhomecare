      </div>
      <div class="svc-longform">
        <div class="svc-block">
          <span class="svc-block-num">Component 01</span>
          <h3>Waking Night Cover</h3>
          <p>A waking night means the carer is awake and present throughout, actively available for the whole period rather than asleep and on call.</p>
          <p>This is the right choice where the night genuinely involves work: somebody who gets up several times, needs repositioning through the night, requires continence support, becomes agitated or disoriented after dark, or has a clinical need that has to be attended to at set hours.</p>
          <p>It costs more than sleeping cover, and we will tell you honestly when it is not necessary &mdash; but where it is needed, sleeping cover is not a substitute and pretending otherwise would be unsafe.</p>
          <ul class="svc-block-list">
            <li>A carer awake throughout the night</li>
            <li>Immediate response, not woken response</li>
            <li>Regular checks and repositioning</li>
            <li>Support to the bathroom at any hour</li>
            <li>Management of night-time agitation and sundowning</li>
            <li>Continuous supervision where wandering is a risk</li>
          </ul>
        </div>
        <div class="svc-block">
          <span class="svc-block-num">Component 02</span>
          <h3>Sleeping Night Cover</h3>
          <p>A sleeping night means the carer is in the house and sleeping, available to be woken if needed but not up throughout.</p>
          <p>This suits situations where the person usually sleeps through, but where being alone is unsafe or frightening &mdash; a fall risk, someone recently bereaved, someone recovering from a hospital stay, or a household where the reassurance of another person in the house is the main thing needed.</p>
          <p>We assess honestly which type your situation calls for. Choosing sleeping cover to save money when the night genuinely involves work is a false economy that fails the person and the carer.</p>
          <ul class="svc-block-list">
            <li>A carer present in the house overnight</li>
            <li>Available to be woken when needed</li>
            <li>Response to falls, distress or illness</li>
            <li>Reassurance for someone anxious alone at night</li>
            <li>Settling before sleep and support in the morning</li>
            <li>Honest assessment of whether this is sufficient</li>
          </ul>
        </div>
        <div class="svc-block">
          <span class="svc-block-num">Component 03</span>
          <h3>The Evening Settle and Morning Start</h3>
          <p>Overnight care is not only the hours of darkness. The value often sits at either end &mdash; the settle before bed and the start of the morning.</p>
          <p>The evening routine matters especially where there is dementia: a calm, familiar sequence at a consistent time does more to prevent a difficult night than anything attempted once agitation has already set in. In the morning, being helped up, washed and dressed means the carer wakes to a household already underway rather than to a shift already starting.</p>
          <ul class="svc-block-list">
            <li>Support with the evening routine and settling</li>
            <li>Consistent bedtime sequence</li>
            <li>Medication at prescribed evening times</li>
            <li>Morning wake, washing and dressing support</li>
            <li>Breakfast preparation</li>
            <li>Handover to daytime carers or family</li>
          </ul>
        </div>
        <div class="svc-block">
          <span class="svc-block-num">Component 04</span>
          <h3>Managing Night-Time Confusion</h3>
          <p>Sundowning &mdash; increased confusion, agitation and restlessness in the evening and night &mdash; is one of the most difficult things families deal with, and one of the most common reasons they conclude they can no longer cope at home.</p>
          <p>Handled well it is frequently manageable. That means consistent routine, low stimulation, familiar surroundings kept unchanged, calm redirection rather than correction, and a carer who is not themselves exhausted and short-tempered at two in the morning. An unrested family member cannot reliably provide that; a carer starting a shift can.</p>
          <ul class="svc-block-list">
            <li>Consistent, calm evening routine</li>
            <li>Low-stimulation environment management</li>
            <li>Calm redirection rather than confrontation</li>
            <li>Familiar objects and surroundings maintained</li>
            <li>Safe supervision during night-time wandering</li>
            <li>Documented patterns to inform the care plan</li>
          </ul>
        </div>
        <div class="svc-block">
          <span class="svc-block-num">Component 05</span>
          <h3>Night Care Tasks and Safety</h3>
          <p>Where the night involves practical work, that work gets done properly rather than by an exhausted relative doing unsafe lifts in the dark.</p>
          <p>That includes repositioning to prevent pressure injuries, continence support, help to and from the bathroom, and immediate response if a fall or acute change occurs &mdash; the difference between being found in minutes and being found at breakfast.</p>
          <ul class="svc-block-list">
            <li>Repositioning and pressure area care</li>
            <li>Continence and toileting support overnight</li>
            <li>Safe transfers in low light</li>
            <li>Immediate response to falls</li>
            <li>Recognition of acute change and escalation</li>
            <li>Nursing cover where clinical tasks are involved</li>
          </ul>
        </div>
        <div class="svc-block">
          <span class="svc-block-num">Component 06</span>
          <h3>What It Gives the Family Carer</h3>
          <p>The clinical description of this service undersells what it actually delivers, which is sleep for the person who has not had any.</p>
          <p>Chronic sleep deprivation is the most common reason home caring arrangements collapse. It degrades judgement, patience and physical health, and it is cumulative. Restoring a carer's nights is frequently what allows an arrangement everyone assumed was finished to continue for years.</p>
          <ul class="svc-block-list">
            <li>Uninterrupted sleep for the family carer</li>
            <li>Relief from night-time responsibility</li>
            <li>Reduced risk of carer injury from night lifting</li>
            <li>Regular nights or occasional cover as needed</li>
            <li>Written record of how each night went</li>
            <li>Honest advice on whether the arrangement is sustainable</li>
          </ul>
