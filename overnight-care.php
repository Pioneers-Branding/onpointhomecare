            <span class="faq-q-icon">+</span>
          </button>
          <div class="faq-content">
            <p>Commonly around ten in the evening to seven in the morning, but the hours are set to fit the household. Many families extend the start so the evening settle is included, since that is often where a lot of the value sits.</p>
          </div>
        </div>
