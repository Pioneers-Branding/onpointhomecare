            <span class="faq-q-icon">+</span>
          </button>
          <div class="faq-content">
            <p>Yes. Some families use it every night, some two nights a week to guarantee the carer gets proper sleep, and some only for a specific period after a hospital discharge or during an illness. Regular predictable nights tend to help the carer most, but occasional cover is a perfectly reasonable way to use it.</p>
          </div>
