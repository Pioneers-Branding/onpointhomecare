          <h2 id="healthcare">Surrey Memorial, Peace Arch, and Discharge Planning</h2>
          <p><strong>Surrey Memorial Hospital</strong>, located at 13750 96 Avenue, is a major Fraser Health acute care and trauma centre serving Surrey and much of the surrounding Fraser Valley. In South Surrey and White Rock, <strong>Peace Arch Hospital</strong> is the local acute care facility, providing emergency and surgical services closer to that part of the city. Because these two hospitals serve different parts of Surrey, the practical distance from home to hospital, and back home again after discharge, varies significantly depending on where in the city your parent lives.</p>
          <p>Whichever hospital is involved, the discharge window is often the highest-risk period for a fall, medication error, or unplanned readmission. Our <a href="hospital-to-home-care">hospital-to-home care</a> and <a href="post-discharge-nursing">post-discharge nursing</a> services are built to get a caregiver or nurse in place quickly once discharge planning begins, reducing that risk during the first fragile days at home.</p>
          <p>Surrey's SkyTrain network, the Expo Line running through City Centre and the Millennium Line extension serving Fleetwood, has made it easier for family members to visit a parent regularly even without a car, but it has not shortened the physical distance between, say, Cloverdale and Peace Arch Hospital. When you're comparing providers, it's worth asking directly how they staff South Surrey and the more eastern communities, since a company based only near City Centre may struggle to offer the same visit reliability further out.</p>

          <h2 id="services">Home Care Services Available in Surrey</h2>
          <p>Home care ranges from a few hours of weekly companionship to full-time nursing supervision, and the right starting point depends on your loved one's health and safety needs. Services Surrey families commonly request include:</p>
          <ul>
            <li><a href="personal-care">Personal care</a>: help with bathing, dressing, and daily hygiene routines.</li>
            <li><a href="companion-care">Companion care</a>: friendly support, light housekeeping, meal prep, and rides to appointments or errands.</li>
            <li><a href="dementia-care">Dementia care</a>: consistent routines and safety monitoring for clients with memory loss.</li>
            <li><a href="complex-care-at-home">Complex care at home</a>: nursing-level support for clients managing multiple chronic conditions.</li>
            <li><a href="24-hour-nursing-care">24-hour nursing care</a>: continuous clinical support for higher-acuity needs.</li>
            <li><a href="caregiver-burnout">Respite support</a> for family members who have been providing care solo and need a break.</li>
          </ul>
          <p>Because Surrey's population and housing stock are so varied, we build each plan around a clinical assessment rather than a fixed package. Our full <a href="services">home care services</a> page outlines everything available if you want to explore options before booking an assessment.</p>

