          <h2 id="costs">What Home Care Costs in Surrey</h2>
          <p>As in the rest of Metro Vancouver, home care in Surrey is typically priced by the hour, with total cost driven by weekly hours needed and whether a caregiver, Licensed Practical Nurse, or Registered Nurse is required. A few hours of weekly companion care costs far less than continuous nursing support, and many families start smaller and increase hours as needs change. Our <a href="home-care-cost">home care cost guide</a> explains the main pricing factors, though the most accurate number comes from a free in-home assessment specific to your parent's needs and location within Surrey.</p>

          <h2 id="getting-started">How to Get Started</h2>
          <p>Getting started is the same three-step process wherever you live in Surrey: a conversation about what's changed at home, an in-home assessment where a nurse evaluates safety and medical needs, and a proposed plan matched to a caregiver who already knows your part of the city. The assessment step is what turns a vague worry into a concrete plan with real hours and a real caregiver.</p>
          <p>If you're ready to talk through what you're seeing, reach out through our <a href="contact">contact page</a>, or request a free <a href="care-assessment">in-home care assessment</a> to get a plan built around your family's specific situation in Surrey.</p>

