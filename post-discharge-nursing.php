      <div class="svc-longform">
        <div class="svc-block">
          <span class="svc-block-num">Component 01</span>
          <h3>Translating the Discharge Summary Into a Workable Plan</h3>
          <p>A discharge summary is written by clinicians for clinicians. It records what happened in hospital and what should happen next, in language that assumes a professional reader and a functioning household.</p>
          <p>The first nursing visit takes that document and works through it in the actual home. What does 'mobilise as tolerated' mean when the bathroom is upstairs? What does 'monitor for signs of infection' actually look like on this incision? Which of these six follow-ups is the urgent one?</p>
          <p>The output is a plain-language plan the family can follow, and a nursing schedule for the parts they should not be doing alone.</p>
          <ul class="svc-block-list">
            <li>Full review of discharge documentation</li>
            <li>Plain-language explanation for the family</li>
            <li>Identification of the highest-risk instructions</li>
            <li>Practical adaptation to the actual home</li>
            <li>Written schedule of nursing visits</li>
            <li>Clear list of warning signs and who to call</li>
          </ul>
        </div>
        <div class="svc-block">
          <span class="svc-block-num">Component 02</span>
          <h3>Medication Reconciliation</h3>
          <p>This is where most post-discharge problems begin. A hospital stay commonly changes several medications at once. Meanwhile the old packets are still in the cupboard, and nobody has told the community pharmacy.</p>
          <p>Our nurses physically go through what is in the house, compare it against the discharge medication list, identify what should have stopped, what is new, what is duplicated under a different brand name, and what has not been dispensed at all. Discrepancies go straight back to the prescriber.</p>
          <ul class="svc-block-list">
            <li>Physical review of all medications in the home</li>
            <li>Comparison against the discharge medication list</li>
            <li>Identification of duplicates and discontinued drugs</li>
            <li>Confirmation that new prescriptions were dispensed</li>
            <li>Administration support and dosette setup</li>
            <li>Direct escalation of discrepancies to the prescriber</li>
          </ul>
        </div>
        <div class="svc-block">
          <span class="svc-block-num">Component 03</span>
          <h3>Wound and Surgical Site Monitoring</h3>
          <p>Incisions and wounds are checked on a defined schedule by someone who knows the difference between normal post-surgical inflammation and the beginning of an infection.</p>
          <p>Dressings are changed under sterile technique, the site is measured and documented, and the family is shown what to look for between visits &mdash; specifically what warrants a phone call rather than waiting for the next scheduled visit.</p>
          <ul class="svc-block-list">
            <li>Scheduled surgical site inspection</li>
            <li>Sterile dressing changes</li>
            <li>Documented wound measurement and photography where appropriate</li>
            <li>Early infection sign identification</li>
            <li>Family education on warning signs</li>
            <li>Escalation to the surgical team when indicated</li>
          </ul>
        </div>
        <div class="svc-block">
          <span class="svc-block-num">Component 04</span>
          <h3>Symptom and Vital Sign Surveillance</h3>
          <p>The first visit establishes a baseline: what this person's blood pressure, oxygen saturation, temperature, pain level, appetite and mental state look like now that they are home.</p>
          <p>Every subsequent visit measures against that baseline. Deterioration in the weeks after discharge is often gradual &mdash; a little more breathless each day, eating a little less, a bit more confused &mdash; and gradual change is exactly what a family living with it day to day cannot see.</p>
          <ul class="svc-block-list">
            <li>Baseline observations at the first visit</li>
            <li>Scheduled vital signs monitoring</li>
            <li>Pain assessment and scoring</li>
            <li>Appetite, fluid intake and weight tracking</li>
            <li>Confusion, mood and cognition observation</li>
            <li>Documented trend reporting</li>
          </ul>
        </div>
        <div class="svc-block">
          <span class="svc-block-num">Component 05</span>
          <h3>Rebuilding Mobility After Hospital Deconditioning</h3>
          <p>Bed rest costs muscle strength quickly, and older adults lose it faster and regain it slower. Someone discharged after a week of illness is frequently at real risk of a fall in their own home &mdash; a fall that would put them straight back on a ward.</p>
          <p>Nursing support means supervised movement at a safe pace, a reassessment of fall risk in the current condition rather than the pre-admission one, and practical adjustments to the house while recovery is happening.</p>
          <ul class="svc-block-list">
            <li>Post-admission fall risk reassessment</li>
            <li>Supervised mobility and safe transfers</li>
            <li>Home hazard review in light of reduced strength</li>
            <li>Equipment and aid recommendations</li>
            <li>Graded activity progression</li>
            <li>Coordination with physiotherapy where involved</li>
          </ul>
        </div>
        <div class="svc-block">
          <span class="svc-block-num">Component 06</span>
          <h3>Follow-Up and Appointment Coordination</h3>
          <p>Discharge usually generates a list of follow-ups: a surgical review, blood work, a specialist appointment, a family physician visit. Each one exists for a reason, and each one is easy to lose in a difficult few weeks.</p>
          <p>We help keep that list visible, prepare for the appointments so the clinician gets useful information, and make sure the results of our own monitoring reach the people making decisions.</p>
          <ul class="svc-block-list">
            <li>Tracking of scheduled follow-up appointments</li>
            <li>Preparation of observations for review appointments</li>
            <li>Written summaries sent to the family physician</li>
            <li>Coordination with specialists and clinics</li>
            <li>Handover to ongoing services where needed</li>
            <li>Clear discharge from our own service when appropriate</li>
          </ul>
        </div>
      </div>

