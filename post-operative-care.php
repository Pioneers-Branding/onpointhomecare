        <h2 class="section-heading">What Post-Operative Care Actually Involves</h2>
        <p class="section-subheading">The plan is written against the specific procedure and the surgeon's instructions. These are the areas it covers.</p>
      </div>
      <div class="svc-longform">
        <div class="svc-block">
          <span class="svc-block-num">Component 01</span>
          <h3>Surgical Site Care and Infection Surveillance</h3>
          <p>The incision is inspected on a defined schedule by someone who knows what normal healing looks like at day three, day seven and day fourteen for that type of procedure &mdash; and therefore knows when something is off.</p>
          <p>Dressing changes are done under sterile technique with the products the surgical team specified. The site is measured and documented at each visit so that change over time is visible in a record rather than reconstructed from memory.</p>
          <p>Surgical site infection is the complication we are most alert to, because it is common, it escalates quickly in older adults, and caught early it is usually manageable at home.</p>
          <ul class="svc-block-list">
            <li>Scheduled incision inspection and assessment</li>
            <li>Sterile dressing changes to the surgical protocol</li>
            <li>Documented measurement and healing tracking</li>
            <li>Redness, heat, swelling, discharge and odour monitoring</li>
            <li>Temperature and systemic infection sign checks</li>
            <li>Direct escalation to the surgical team when indicated</li>
          </ul>
        </div>
        <div class="svc-block">
          <span class="svc-block-num">Component 02</span>
          <h3>Pain Assessment and Medication Management</h3>
          <p>Pain after surgery is not just a comfort issue. Poorly controlled pain stops people moving, and not moving is what causes pneumonia, blood clots and the muscle loss that turns a two-week recovery into a three-month one.</p>
          <p>Equally, over-sedation in an older adult causes confusion, constipation and falls. The job is to get this balance right, and that requires proper assessment rather than asking 'how are you feeling?' at the door.</p>
          <p>Our nurses assess and score pain systematically, supervise the prescribed regimen, watch for side effects, and give the prescriber real information when an adjustment is needed.</p>
          <ul class="svc-block-list">
            <li>Structured pain assessment and scoring</li>
            <li>Supervision of the prescribed analgesic regimen</li>
            <li>Opioid side effect monitoring (sedation, constipation, confusion)</li>
            <li>Assessment of whether pain is limiting recovery activity</li>
            <li>Documentation to support prescriber adjustments</li>
            <li>Non-pharmacological comfort measures</li>
          </ul>
        </div>
        <div class="svc-block">
          <span class="svc-block-num">Component 03</span>
          <h3>Safe Re-Mobilization</h3>
          <p>Getting moving again is the single most important thing a post-surgical patient does, and the thing they are most likely to avoid &mdash; because it hurts, and because they are frightened of falling or damaging the repair.</p>
          <p>Nursing support means movement happens, on a graded schedule, with somebody there. It also means the surgeon's precautions are actually observed: weight-bearing status, movement restrictions, lifting limits.</p>
          <ul class="svc-block-list">
            <li>Supervised mobility within surgical precautions</li>
            <li>Safe transfer technique (bed, chair, toilet, stairs)</li>
            <li>Fall risk assessment in the post-operative state</li>
            <li>Graded activity progression against recovery goals</li>
            <li>Reinforcement of weight-bearing and movement restrictions</li>
            <li>Coordination with physiotherapy where involved</li>
          </ul>
        </div>
        <div class="svc-block">
          <span class="svc-block-num">Component 04</span>
          <h3>Post-Anaesthetic and Systemic Effects</h3>
          <p>Anaesthetic and surgery affect far more than the operative site. Older adults commonly experience post-operative confusion, constipation, urinary retention, nausea, dizziness and disturbed sleep.</p>
          <p>These are frequently dismissed as 'just how they are after an operation' &mdash; but post-operative delirium in particular is a genuine clinical event that needs recognising, and constipation from opioids can become an emergency if left.</p>
          <ul class="svc-block-list">
            <li>Post-operative delirium and confusion monitoring</li>
            <li>Bowel function tracking and constipation prevention</li>
            <li>Urinary output and retention observation</li>
            <li>Nausea and appetite management</li>
            <li>Blood clot warning sign awareness (DVT/PE)</li>
            <li>Sleep and orientation support</li>
          </ul>
        </div>
        <div class="svc-block">
          <span class="svc-block-num">Component 05</span>
          <h3>Nutrition, Hydration and Healing</h3>
          <p>Tissue repair requires protein, calories and fluid, and appetite after surgery is frequently poor. An older adult who eats little for a fortnight will heal slowly and lose strength they will struggle to rebuild.</p>
          <p>We track intake honestly rather than accepting 'she's eating fine', monitor hydration, and flag when nutritional intake is genuinely inadequate for the healing that is being asked of the body.</p>
          <ul class="svc-block-list">
            <li>Food and fluid intake monitoring</li>
            <li>Weight tracking through the recovery period</li>
            <li>Dehydration sign recognition</li>
            <li>Support with meals where required</li>
            <li>Protein and nutrition guidance for healing</li>
            <li>Escalation where intake is clinically inadequate</li>
          </ul>
        </div>
        <div class="svc-block">
          <span class="svc-block-num">Component 06</span>
          <h3>Reporting Back to the Surgical Team</h3>
          <p>The surgeon sees the patient at the follow-up appointment and asks how recovery has gone. The answer is usually a family member's best recollection of a difficult few weeks.</p>
          <p>Our documented observations replace that with something useful: what the wound has actually done, what the pain scores have been, how mobility has progressed, and what complications arose and when.</p>
          <ul class="svc-block-list">
            <li>Written recovery notes for the family</li>
            <li>Documented observations for the follow-up appointment</li>
            <li>Direct escalation when something falls outside expectations</li>
            <li>Coordination with the family physician</li>
            <li>Handover to ongoing services if recovery is prolonged</li>
            <li>Clear discharge when recovery is complete</li>
          </ul>
        </div>
      </div>

