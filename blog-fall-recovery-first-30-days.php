          <h2 id="weeks-two-three">Days 8 to 21: Rebuilding Routine and Mobility</h2>
          <p>By the second and third week, most people without a major fracture are steadily increasing their activity, and those recovering from surgery are usually well into a structured physiotherapy program, whether at a rehabilitation facility or through home visits. This is the period where consistency matters more than intensity. Older adults recovering from a fall often benefit from physiotherapy that rebuilds balance and mobility gradually, and skipping sessions or pushing too hard on a single "good day" both tend to slow overall progress.</p>
          <p>This is also when household routines need to adapt, at least temporarily: meal preparation, medication management, and getting safely to and from the bathroom may all need extra support while strength and confidence are still returning. For families managing this alongside surgery or a hospital stay, our guide to <a href="hospital-to-home-care">hospital-to-home care</a> covers the discharge side of this transition in more detail.</p>

          <h2 id="week-four">Days 22 to 30: Confidence, Fear of Falling, and What Comes Next</h2>
          <p>Physically, many people are noticeably stronger by the fourth week, though fractures and surgical recovery generally take considerably longer, often 8 to 12 weeks or more before full healing. What surprises many families more is the psychological side: research on fear of falling has found that a large majority of older adults report ongoing fear of falling again in the weeks following a fall, even those without a new injury. That fear is not irrational, and it is not something to argue someone out of. Left unaddressed, though, it can cause a person to quietly restrict their own activity, which weakens them further and paradoxically increases fall risk.</p>
          <p>The most effective response tends to be practical rather than reassuring: continued physiotherapy or supervised exercise, a home environment that has been checked for hazards, and small, repeated successes, a walk to the mailbox and back, a shower managed safely, that rebuild trust in the body gradually.</p>

          <div class="quote-card-teal">
            <strong>From our clinical experience:</strong> The families who do best in this first month are the ones who treat "getting back to normal" as a gradual process with milestones, not a single date to return to. Expecting too much too soon is almost always what triggers setbacks or a second fall.
          </div>

          <h2 id="warning-signs">Warning Signs That Need Medical Attention</h2>
          <p>Most recoveries proceed without complication, but a few signs during the first 30 days warrant a prompt call to a physician or a return to urgent care: new or worsening confusion, a limb that suddenly won't bear weight, pain that is getting worse rather than better, a wound that looks red, swollen, or is draining, or any head injury symptoms such as unusual drowsiness, vomiting, or slurred speech appearing after the initial evaluation. Shortness of breath or calf swelling after a period of reduced mobility should also be checked promptly, as prolonged inactivity can occasionally contribute to blood clots. When in doubt, it is always reasonable to seek medical advice rather than wait and see.</p>

          <h2 id="how-support-helps">How Home Support Helps During Recovery</h2>
          <p>A lot of what makes the first 30 days go well is unglamorous: someone available to help with a safe transfer to the bathroom, a second pair of hands for meal preparation, a reminder to take medication on schedule, and simply having another adult in the home during the hours when a fall is most likely to happen again. For many families, that support is what allows a parent to recover at home at all, rather than a longer stay in a rehabilitation facility. Whether that looks like a few hours of daily <a href="companion-care">companion care</a>, more hands-on <a href="personal-care">personal care</a> support, or <a href="nursing-health-monitoring">nursing health monitoring</a> during a higher-risk recovery, the right level of support usually shifts as the month progresses, which is exactly why a care plan should be reassessed rather than set once and left alone.</p>
          <p>If you're earlier in this process and looking at the broader picture of what changed after the fall itself, our overview of <a href="care-after-a-fall">care after a fall</a> is a useful starting point alongside this timeline.</p>

          <h2 id="caregiver">Don't Forget the Family Caregiver</h2>
          <p>The first 30 days after a fall usually fall hardest on whichever family member takes the lead: driving to appointments, managing new medications, adjusting their own schedule around someone else's recovery, and quietly worrying about a second fall the whole time. It's common for that person's own sleep, health, and stress levels to slip during exactly the weeks when steady support matters most. If you notice yourself feeling constantly exhausted, resentful, or unable to switch off, it's worth reading about the early <a href="caregiver-burnout">signs of caregiver burnout</a> rather than waiting until you're running on empty.</p>
          <p>Bringing in even a modest amount of outside help, a few hours of <a href="respite-care">respite care</a> each week, or overnight support during the highest-risk early stretch, is not a sign that the family is failing to cope. It's often what allows both the person recovering and the person supporting them to actually get through the month in one piece.</p>

