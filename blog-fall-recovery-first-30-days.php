        <div class="article-body">
          <p>Care after a fall at home does not end once the emergency room visit is over, or once a family member says they're "fine." What happens in the following 30 days often determines whether someone fully regains their independence or slides into a cycle of reduced activity, weakness, and a higher risk of falling again. Families are rarely given a clear roadmap for this period, so they improvise, often erring too far toward rest or too far toward "getting back to normal" before the body is ready.</p>
          <p>This is a general guide to what a safe, realistic recovery timeline tends to look like, based on common clinical patterns. It is not a substitute for guidance from the physician, surgeon, or physiotherapist actually treating the person, and recovery from a fracture, head injury, or surgery will follow a different and longer timeline than recovery from bruising or a soft-tissue strain.</p>

          <h2 id="first-72-hours">The First 24 to 72 Hours: Medical Evaluation Comes First</h2>
          <p>Every fall in an older adult deserves a medical evaluation, even if the person insists they feel okay. Hip and wrist fractures, and head injuries in particular, are not always obvious right away, and some symptoms, confusion, worsening pain, or a bruise that spreads, only appear over the following day or two. If a fracture is confirmed, most hip fractures are treated with surgery, typically within a day or two of the fall, followed by a hospital stay of a few days. During this window, the priorities are diagnosis, pain control, and starting to plan for what discharge and home recovery will actually require.</p>

          <h2 id="week-one">Days 1 to 7: Rest, Pain Control, and Early Movement</h2>
          <p>The first week home is a balancing act. Some rest is necessary, especially after surgery or with significant bruising, but complete bed rest is one of the more common mistakes families make. Muscle strength and balance decline quickly with inactivity, particularly in older adults, which raises the risk of a second fall rather than lowering it. Whenever a physician or physiotherapist has cleared it, small amounts of guided movement, sitting up, standing with support, short supervised walks, should begin early rather than waiting until someone "feels ready."</p>
          <p>Pain management matters here too, not as an end in itself but because uncontrolled pain is often what keeps someone from moving at all. If a walker, cane, or raised toilet seat has been recommended, this first week is when it should already be in place at home, not ordered after the fact.</p>

