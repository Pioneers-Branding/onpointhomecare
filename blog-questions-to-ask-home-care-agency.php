          <h2 id="employees">2. Are Caregivers Employees or Independent Contractors?</h2>
          <p>This distinction matters more than families often realize. When caregivers are employees, the agency is responsible for their training, supervision, payroll deductions, and WorkSafeBC coverage, and it can replace a caregiver who is sick or on leave. When caregivers work as independent contractors booked through a platform, that safety net often disappears, and you may end up coordinating replacement coverage yourself.</p>
          <p>Ask directly: "If something goes wrong during a shift, who is legally and financially responsible?" A clear answer, backed by insurance documentation, tells you far more than a general reassurance that "our caregivers are wonderful."</p>

          <h2 id="screening">3. How Are Caregivers Screened and Trained?</h2>
          <p>Ask specifically about criminal record checks, reference verification, and what training caregivers receive before their first shift, not just at hiring. Dementia care, fall prevention, and safe transfer techniques all require training beyond common sense, and an agency that invests in ongoing education is usually one that takes quality seriously.</p>
          <p>It's reasonable to ask how many years of experience a caregiver typically has before being matched with a family, and whether the agency does in-home supervisory visits to check on the quality of care once a shift schedule is underway, rather than assuming everything is going well once a caregiver is placed.</p>

          <h2 id="nursing">4. Is There a Registered Nurse Involved in the Care Plan?</h2>
          <p>Non-medical home support and nursing-supervised home care are different services, and it's worth knowing which one you're getting. Some agencies pair every client with a Registered Nurse who oversees the care plan and can flag changes in health status early. Others provide caregivers with no clinical oversight at all. Neither approach is automatically wrong, but you should know which model you're paying for.</p>
          <p>This matters even for families who only need companionship or light housekeeping today. Needs tend to change gradually, and an agency with nursing oversight built in can usually scale up support, wound care, medication management, or post-hospital monitoring, without requiring you to start over with a different provider.</p>

          <h2 id="care-plan">5. How Is My Care Plan Created?</h2>
          <p>A reputable agency will not quote a price over the phone without first understanding your parent's specific needs, routines, and home environment. Ask whether the agency conducts an in-home assessment before care begins, who attends it, and how often the plan is reviewed and adjusted as needs change.</p>
          <p>Also ask how much input your parent will have in the plan itself. The families who report the smoothest transition to home care are usually the ones where the older adult helped choose the schedule, the caregiver, and the specific tasks covered, rather than having a plan handed to them.</p>

          <h2 id="backup">6. What Happens if My Regular Caregiver Is Sick or Unavailable?</h2>
          <p>Consistency matters, especially for clients living with dementia, but even the best caregiver eventually needs a sick day or a vacation. Ask what the agency's backup process looks like: is there a pool of trained substitute caregivers, or does a shift simply get cancelled? This single question often reveals more about an agency's operational strength than anything else on this list.</p>
          <p>Ask, too, how a substitute caregiver would be introduced to your parent. A hurried handoff with no notes on routines or preferences can undo a lot of the comfort a familiar caregiver has built, especially for someone who relies on predictability.</p>

          <h2 id="communication">7. How Will You Communicate With My Family?</h2>
          <p>Find out who your main point of contact will be, how often you'll receive updates, and what the process looks like if you have a concern about a shift. Families coordinating care from another city or juggling multiple siblings should ask specifically whether updates can be shared with more than one family member.</p>
          <p>If your family has already run into disagreements about a parent's care, or you expect you might, ask whether the agency will speak with all interested siblings directly, or only with a single designated contact. Getting this arrangement clear at the start prevents a lot of confusion later.</p>

          <h2 id="availability">8. Is Support Available 24/7, Including Evenings and Holidays?</h2>
          <p>Falls, medical concerns, and caregiver no-shows don't wait for business hours. Ask what happens if something comes up on a Saturday night or a holiday Monday, and what response time you can realistically expect.</p>
          <p>If your parent's needs may eventually include overnight supervision or round-the-clock coverage, ask now how the agency scales up staffing for that level of care, rather than waiting until an urgent need arises to find out the answer is "we don't offer that."</p>

          <h2 id="pricing">9. How Is Pricing Structured?</h2>
          <p>Ask for a clear breakdown of hourly rates, minimum shift lengths, and whether rates change on evenings, weekends, or holidays. A trustworthy agency will walk you through pricing on the phone without pressure, and put the details in writing before your first shift. If cost is a major factor in your decision, our guide to <a href="home-care-cost">home care costs in Metro Vancouver</a> breaks down what typically drives the total.</p>
          <p>It's also worth asking about references. A confident agency should be able to connect you with a current or past family, or at least a hospital discharge planner or physician who refers clients to them regularly. Online reviews are a useful starting point, but a short conversation with someone who has actually used the service tells you more.</p>

          <h2 id="funding">10. How Does This Work Alongside Public Funding Options?</h2>
          <p>In British Columbia, some families qualify for home support through Vancouver Coastal Health after a clinical assessment, and others manage their own care through the Choice in Supports for Independent Living (CSIL) program. A knowledgeable agency should be able to explain, in plain language, how private home care can complement public support, whether that means covering extra hours, weekend gaps, or services the public system doesn't provide.</p>
          <p>Under CSIL, a family becomes the employer of record and takes on hiring and scheduling directly, which suits some households and overwhelms others. If you're weighing that option, ask a private agency whether they can still support a CSIL client in a more limited, advisory role, or whether their services are structured as a fully separate, private-pay arrangement.</p>

